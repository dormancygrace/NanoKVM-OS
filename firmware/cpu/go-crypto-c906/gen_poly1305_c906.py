#!/usr/bin/env python3
"""Generate sum_c906_riscv64.s, Poly1305 for Go's vendored x/crypto, from
CRYPTOGAMS poly1305-riscv.pl.

The same Poly1305 as the kernel's lib/crypto and NanoKVM OpenSSL (patch
0011): the pinned file is the one Linux 7.3.1 builds. CRYPTOGAMS
(BSD-3-Clause, see CRYPTOGAMS-LICENSE) is assembled by GNU as twice, with and
without __riscv_misaligned_fast, and each poly1305_blocks becomes a Go
function of WORDs with the GNU mnemonics in comments; branches are
PC-relative and stay within the function. The Go function updateScalar, written
here, adapts Go's macState (h[3], r[2], s[2]; CRYPTOGAMS wants
s1 = r1 + (r1 >> 2) where Go keeps s) through a context in its frame, pads a
final partial block like OpenSSL does (0x01, zeros, padbit 0), and picks the
blocks function by useMisalignedLoads.

Usage: gen_poly1305_c906.py --cryptogams FILE --binutils PREFIX (--output FILE | --check FILE)
       gen_poly1305_c906.py --print-url
"""
import argparse
import hashlib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

URL = 'https://raw.githubusercontent.com/gregkh/linux/v7.3.1/lib/crypto/riscv/poly1305-riscv.pl'
SHA256 = '9a75fc04cd61e8fbd7f7e7cafec070158fb2d964d33c1d3da3d028e10a0a1a72'

# Registers the CRYPTOGAMS code may use: Go keeps g in x27 and gp/tp fixed;
# everything else is caller-saved in Go's ABI0.
ALLOWED = set('zero ra sp a0 a1 a2 a3 a4 a5 a6 a7 t0 t1 t2 t3 t4 t5 t6 s0 s1 s2 s3'.split())
REG = re.compile(r'\b(zero|ra|sp|gp|tp|[ast][0-9]+|x[0-9]+)\b')
# CRYPTOGAMS saves s0-s3 in a 32-byte frame of its own. Go's ABI0 does not
# need them preserved, and an SP change the Go assembler cannot see would
# break traceback (CPU profiles) inside the function: these become nops, so
# the functions are frameless leaves and the branch offsets stay valid.
FRAME = re.compile(r'^(addi sp,sp,-?32|[sl]d s[0-3],\d+\(sp\))$')
NOP = 0x00000013


def blocks(pl, binutils, fast):
    """(word, mnemonic) of poly1305_blocks, 32-bit encodings only."""
    with tempfile.TemporaryDirectory() as d:
        src = Path(d) / 'p.S'
        subprocess.run(['perl', str(pl), '64', str(src)], check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        defs = ['-D__riscv', '-D__riscv_xlen=64', '-D__SIZEOF_POINTER__=8']
        if fast:
            defs.append('-D__riscv_misaligned_fast')
        # -undef: the same output from a host cpp or a riscv64 compiler.
        text = subprocess.run(['cpp', '-P', '-undef', '-x', 'assembler-with-cpp', *defs, str(src)],
                              check=True, capture_output=True, text=True).stdout
        asm = Path(d) / 'p.s'
        asm.write_text('.option norvc\n' + text)
        obj = Path(d) / 'p.o'
        subprocess.run([binutils + 'as', '-march=rv64gc', '-o', str(obj), str(asm)], check=True)
        syms = subprocess.run([binutils + 'nm', '-S', str(obj)], check=True, capture_output=True,
                              text=True).stdout
        m = re.search(r'^([0-9a-f]+) ([0-9a-f]+) T poly1305_blocks$', syms, re.M)
        start, size = int(m.group(1), 16), int(m.group(2), 16)
        dump = subprocess.run([binutils + 'objdump', '-d', '--start-address', str(start),
                               '--stop-address', str(start + size), str(obj)],
                              check=True, capture_output=True, text=True).stdout
    out = []
    for addr, word, ins in re.findall(r'^\s*([0-9a-f]+):\s+([0-9a-f]{8})\s+(.*)$', dump, re.M):
        ins = ' '.join(ins.split('#')[0].split())
        ins = re.sub(r'\s*<[^>]*>$', '', ins)
        # Branch targets as offsets from the instruction, not section addresses.
        m = re.match(r'(b\w*|j|jal)\s+(.*?)([0-9a-f]+)$', ins)
        if m:
            ins = f'{m.group(1)} {m.group(2)}.{int(m.group(3), 16) - int(addr, 16):+d}'
        bad = set(REG.findall(ins)) - ALLOWED
        if bad:
            sys.exit(f'poly1305_blocks uses {sorted(bad)}: {ins}')
        if FRAME.match(ins):
            out.append((NOP, f'nop (was {ins})'))
            continue
        if re.search(r'\bsp\b', ins):
            sys.exit(f'poly1305_blocks uses the stack pointer: {ins}')
        out.append((int(word, 16), ins))
    if len(out) * 4 != size:
        sys.exit('poly1305_blocks has instructions that are not 32 bits wide')
    if out[-1][1] != 'ret' or sum(i == 'ret' for _, i in out) != 1:
        sys.exit('poly1305_blocks must end in its only ret')
    if sum(w == NOP for w, _ in out) != 10:
        sys.exit('expected the 10 instructions of the s0-s3 frame')
    return out


HEADER = '''\
// Code generated by firmware/cpu/go-crypto-c906/gen_poly1305_c906.py. DO NOT EDIT.

// Copyright 2026 The Go Authors. All rights reserved.
// Use of this source code is governed by a BSD-style
// license that can be found in the LICENSE file.
//
// poly1305BlocksFast and poly1305BlocksAligned are CRYPTOGAMS poly1305_blocks,
// Copyright (c) 2006, CRYPTOGAMS by <appro@openssl.org>, BSD-3-Clause; see
// CRYPTOGAMS-LICENSE. Source: {url},
// sha256 {sha}.

//go:build gc && !purego

#include "textflag.h"

// updateScalar hashes msg into state. Whole blocks go to CRYPTOGAMS poly1305_blocks
// with a context in the frame: h0, h1, h2, r0, r1 and s1 = r1 + (r1 >> 2)
// at 8..55(SP) (Go keeps s, the final key half, where CRYPTOGAMS keeps s1). A
// final partial block (from Sum) is copied to 56(SP), followed by 0x01 and
// zeros, and hashed with padbit 0. The blocks functions take the context,
// message, length and padbit in a0-a3 and clobber a0-a7, t0-t6 and s0-s3;
// they do not touch the stack pointer (the 10 instructions of CRYPTOGAMS'
// own s0-s3 frame are nops), so Go's traceback sees frameless leaves.
//
// CRYPTOGAMS reduces h2 when the next block starts, so h2 can be large after
// the last one; finalize needs h < 2 * (2^130 - 5). updateScalar folds
// 5 * (h2 >> 2) into h0 and keeps h2 & 3, as CRYPTOGAMS poly1305_emit does
// first: then h2 <= 4.
//
// func updateScalar(state *macState, msg []byte)
TEXT ·updateScalar(SB), $72-32
	MOV	state+0(FP), X5
	MOV	0(X5), X6
	MOV	X6, 8(X2)
	MOV	8(X5), X6
	MOV	X6, 16(X2)
	MOV	16(X5), X6
	MOV	X6, 24(X2)
	MOV	24(X5), X6
	MOV	X6, 32(X2)
	MOV	32(X5), X7
	MOV	X7, 40(X2)
	SRL	$2, X7, X6
	ADD	X7, X6
	MOV	X6, 48(X2)
	MOV	msg_base+8(FP), X11
	MOV	msg_len+16(FP), X12
	AND	$-16, X12
	BEQZ	X12, tail
	ADD	$8, X2, X10
	MOV	$1, X13
	MOVBU	·useMisalignedLoads(SB), X14
	BEQZ	X14, aligned
	CALL	·poly1305BlocksFast(SB)
	JMP	tail
aligned:
	CALL	·poly1305BlocksAligned(SB)
tail:
	MOV	msg_len+16(FP), X12
	AND	$15, X12, X13
	BEQZ	X13, done
	MOV	msg_base+8(FP), X11
	AND	$-16, X12
	ADD	X12, X11
	MOV	ZERO, 56(X2)
	MOV	ZERO, 64(X2)
	ADD	$56, X2, X15
copy:
	MOVBU	(X11), X16
	MOVB	X16, (X15)
	ADD	$1, X11
	ADD	$1, X15
	SUB	$1, X13
	BNEZ	X13, copy
	MOV	$1, X16
	MOVB	X16, (X15)
	ADD	$8, X2, X10
	ADD	$56, X2, X11
	MOV	$16, X12
	MOV	ZERO, X13
	CALL	·poly1305BlocksAligned(SB)
done:
	MOV	8(X2), X6
	MOV	16(X2), X7
	MOV	24(X2), X28
	AND	$-4, X28, X29
	SRL	$2, X28, X30
	ADD	X30, X29
	AND	$3, X28
	ADD	X29, X6
	SLTU	X29, X6, X30
	ADD	X30, X7
	SLTU	X30, X7, X30
	ADD	X30, X28
	MOV	state+0(FP), X5
	MOV	X6, 0(X5)
	MOV	X7, 8(X5)
	MOV	X28, 16(X5)
	RET
'''


def render(fast, aligned):
    text = HEADER.format(url=URL, sha=SHA256)
    for name, code, what in [('poly1305BlocksFast', fast, 'with 64-bit loads at any alignment'),
                             ('poly1305BlocksAligned', aligned, 'with aligned loads only')]:
        text += f'\n// {name}: CRYPTOGAMS poly1305_blocks {what}.\n'
        text += f'TEXT ·{name}(SB), NOSPLIT|NOFRAME, $0-0\n'
        text += ''.join(f'\tWORD\t$0x{w:08x}\t// {i}\n' for w, i in code)
    return text


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--print-url', action='store_true', help='print the pinned source URL and exit')
    p.add_argument('--cryptogams', type=Path)
    p.add_argument('--binutils')
    g = p.add_mutually_exclusive_group()
    g.add_argument('--output', type=Path)
    g.add_argument('--check', type=Path)
    a = p.parse_args()
    if a.print_url:
        print(URL)
        return
    if not (a.cryptogams and a.binutils and (a.output or a.check)):
        p.error('--cryptogams, --binutils and --output or --check are required')
    digest = hashlib.sha256(a.cryptogams.read_bytes()).hexdigest()
    if digest != SHA256:
        sys.exit(f'{a.cryptogams}: sha256 {digest}, pinned {SHA256}')
    text = render(blocks(a.cryptogams, a.binutils, True), blocks(a.cryptogams, a.binutils, False))
    if a.check:
        if a.check.read_text() != text:
            sys.exit(f'{a.check} is not up to date')
        print(f'{a.check}: up to date')
    else:
        a.output.write_text(text)
        print(f'{a.output}: written')


if __name__ == '__main__':
    main()
