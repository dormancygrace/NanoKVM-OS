#!/usr/bin/env python3
"""Generate nanokvm_memclr_riscv64.s, the XTheadVector loop of memclrNoHeapPointers.

prepare.py makes runtime.memclrNoHeapPointers jump here for at least
nanokvmVectorMemclrMin bytes when nanokvmVectorMemclr is set (see
nanokvm_memclr.go). Vector instructions are WORDs, encoded and checked
against GNU as/objdump by the encoder of ../go-crypto-c906/gen_chacha_riscv64.py.

Usage: gen_memclr_c906.py --binutils PREFIX (--output FILE | --check FILE)
"""
from pathlib import Path
import argparse, sys

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'go-crypto-c906'))
from gen_chacha_riscv64 import ABI, Asm, FUNCT6, OPIVX, V, opv, vsetvli, vse, verify  # noqa: E402

# Go register numbers. memclrNoHeapPointers' arguments arrive in X10-X11
# (ABIInternal); X0 is the zero register.
PTR, N, ZERO = 10, 11, 0
COUNT, LIMIT, VL, BYTES = 5, 9, 13, 14
LMUL = 4  # 64 bytes per store at VLEN 128, as in gen_memmove_c906.py
ABI = {**ABI, ZERO: 'zero'}


def vsetvli_max(rd, sew, lmul):
    # rs1 = zero, rd != zero: vl = VLMAX.
    v = vsetvli(rd, COUNT, sew, lmul)
    return V(f'th.vsetvli {ABI[rd]},zero,e{sew},m{lmul},d1', v.word & ~(31 << 15))


def vzero(vd):
    return V(f'th.vmv.v.x v{vd},zero', opv(FUNCT6['vmv'], 1, 0, ZERO, OPIVX, vd))


def build():
    a = Asm()
    a('TEXT runtime·nanokvmMemclrVector(SB),NOSPLIT|NOFRAME,$0')
    a('// X10 = ptr, X11 = n; n >= nanokvmVectorMemclrMin, so at least 7 whole')
    a('// words remain after the head.')
    a('// Bytes up to an 8-byte boundary, then 8-byte elements, then the last')
    a('// n%8 bytes. memclrNoHeapPointers must clear each aligned pointer-sized')
    a('// word at once; each one is a single element. Byte elements are slower')
    a('// than the scalar loop for large clears, so none are used.')
    a(f'AND\t$7, X{PTR}, X{COUNT}', f'BEQZ\tX{COUNT}, words')
    a(f'MOV\t$8, X{LIMIT}', f'SUB\tX{COUNT}, X{LIMIT}, X{COUNT}', f'SUB\tX{COUNT}, X{N}')
    a.label('head')
    a(f'MOVB\tZERO, 0(X{PTR})', f'ADD\t$1, X{PTR}', f'SUB\t$1, X{COUNT}', f'BNEZ\tX{COUNT}, head')
    a.label('words')
    a(f'AND\t$7, X{N}, X{COUNT}', f'SRL\t$3, X{N}')
    # Zero the whole register group once; each store then writes VL words.
    a(vsetvli_max(VL, 64, LMUL), vzero(0), vsetvli(VL, N, 64, LMUL))
    a.label('loop')
    a(vse(0, PTR), f'SLL\t$3, X{VL}, X{BYTES}', f'ADD\tX{BYTES}, X{PTR}',
      f'SUB\tX{VL}, X{N}', vsetvli(VL, N, 64, LMUL), f'BNEZ\tX{N}, loop')
    a(f'BEQZ\tX{COUNT}, done')
    a.label('tail')
    a(f'MOVB\tZERO, 0(X{PTR})', f'ADD\t$1, X{PTR}', f'SUB\t$1, X{COUNT}', f'BNEZ\tX{COUNT}, tail')
    a.label('done')
    a('RET')
    return a


HEADER = '''// Code generated by gen_memclr_c906.py; DO NOT EDIT.

// Copyright 2026 NanoKVM OS contributors.
// Use of this source code is governed by a BSD-style license matching Go.

// memclrNoHeapPointers' loop for XTheadVector (T-Head C906, VLEN 128):
// unit-stride stores of a zeroed LMUL 4 register group, 64 bytes each.
//
// Vector registers are not preserved across calls; this code calls nothing.
// Assembly functions are not asynchronously preempted; the kernel saves
// vector state across context switches and signals.
//
// Go's assembler has no RVV 0.7.1 encodings, so vector instructions are WORDs.
// The generator checks each against GNU as/objdump -march=rv64gc_xtheadvector.

#include "textflag.h"

'''


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--binutils', required=True, help='GNU binutils prefix with XTheadVector support')
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument('--output', type=Path)
    g.add_argument('--check', type=Path)
    args = p.parse_args()
    a = build()
    n = verify(args.binutils, a.vectors)
    text = HEADER + a.render()
    if args.check:
        if args.check.read_text() != text:
            sys.exit(f'{args.check} is not up to date')
        print(f'{args.check}: up to date, {n} distinct vector encodings verified')
    else:
        args.output.write_text(text)
        print(f'{args.output}: {len(a.vectors)} vector instructions, {n} distinct encodings verified')


if __name__ == '__main__':
    main()
