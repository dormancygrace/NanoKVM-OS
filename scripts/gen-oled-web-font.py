#!/usr/bin/env python3
"""Write web/src/lib/oled/font.ts from kvm_system's oled_font.h, so that the
OLED editor draws with the device's glyphs. --check compares instead."""
import argparse
import re
from pathlib import Path

repo = Path(__file__).resolve().parents[1]
header = repo / 'support/kvm_system/main/lib/oled_ctrl/oled_font.h'
target = repo / 'web/src/lib/oled/font.ts'

# The state icons of the earlier OLED main page (b24eafc4^, oled_kvm_0621):
# one byte per column, the low bit at the top, seven rows.
icons = {
    'HDMI': ([0x00, 0x3e, 0x08, 0x08, 0x3e, 0x00, 0x3e, 0x22, 0x22, 0x1c, 0x00, 0x3c, 0x02, 0x0c, 0x02, 0x3c,
              0x00, 0x22, 0x3e, 0x22, 0x00],
             [0x3e, 0x41, 0x77, 0x77, 0x41, 0x7f, 0x41, 0x5d, 0x5d, 0x63, 0x7f, 0x43, 0x7d, 0x73, 0x7d, 0x43,
              0x7f, 0x5d, 0x41, 0x5d, 0x3e]),
    'USB': ([0x00, 0x3e, 0x08, 0x08, 0x3e, 0x00, 0x22, 0x3e, 0x20, 0x00, 0x3e, 0x22, 0x22, 0x1c, 0x00],
            [0x3e, 0x41, 0x77, 0x77, 0x41, 0x7f, 0x5d, 0x41, 0x5f, 0x7f, 0x41, 0x5d, 0x5d, 0x63, 0x3e]),
    'ETH': ([0x00, 0x3e, 0x2a, 0x2a, 0x22, 0x00, 0x02, 0x3e, 0x02, 0x00, 0x3e, 0x08, 0x08, 0x3e, 0x00],
            [0x3e, 0x41, 0x55, 0x55, 0x5d, 0x7f, 0x7d, 0x41, 0x7d, 0x7f, 0x41, 0x77, 0x77, 0x41, 0x3e]),
    'WiFi': ([0x00, 0x1e, 0x20, 0x18, 0x20, 0x1e, 0x00, 0x3a, 0x00, 0x3e, 0x0a, 0x0a, 0x00, 0x3a, 0x00],
             [0x3e, 0x61, 0x5f, 0x67, 0x5f, 0x61, 0x7f, 0x45, 0x7f, 0x41, 0x75, 0x75, 0x7f, 0x45, 0x3e]),
}


def table(name, text):
    body = re.search(r'const uint8_t ' + name + r'\[\]\[\d+\]\s*=\s*\{(.*?)\n\};', text, re.S).group(1)
    rows = []
    for line in body.split('\n'):
        line = line.strip()
        if not line.startswith('{'):
            continue  # comments and commented-out rows
        rows.append([int(v, 16) for v in re.findall(r'0[xX][0-9a-fA-F]{2}', line.split('}')[0])])
    return rows


def rows_hex(columns, height=7):
    """Column bytes to image rows: whole bytes, most significant bit first."""
    width = len(columns)
    out = bytearray()
    for row in range(height):
        line = bytearray((width + 7) // 8)
        for x, column in enumerate(columns):
            if column >> row & 1:
                line[x // 8] |= 0x80 >> (x % 8)
        out += line
    return out.hex()


def render():
    text = header.read_text(encoding='utf-8')
    fonts = {4: table('oled_asc2_0804', text), 8: table('oled_asc2_0806', text), 16: table('oled_asc2_1608', text)}
    lines = ['// Generated by scripts/gen-oled-web-font.py from',
             '// support/kvm_system/main/lib/oled_ctrl/oled_font.h. Do not edit.', '',
             '// One entry per character from space; one byte per column, low bit at the top',
             '// (the 16-pixel font: eight top columns, then eight bottom ones).',
             'export const fonts: Record<4 | 8 | 16, readonly (readonly number[])[]> = {']
    for size, glyphs in fonts.items():
        lines.append(f'  {size}: [')
        for glyph in glyphs:
            lines.append('    [' + ', '.join(str(v) for v in glyph) + '],')
        lines.append('  ],')
    lines += ['};', '', '// Link state icons, off and on: width x 7 image rows, hex.',
              'export const icons: readonly { name: string; on: boolean; width: number; data: string }[] = [']
    for name, (off, on) in icons.items():
        for state, columns in ((False, off), (True, on)):
            lines.append(f"  {{ name: '{name}', on: {str(state).lower()}, width: {len(columns)}, "
                         f"data: '{rows_hex(columns)}' }},")
    lines.append('];')
    return '\n'.join(lines) + '\n'


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
output = render()
if args.check:
    if not target.exists() or target.read_text(encoding='utf-8') != output:
        raise SystemExit(f'{target.relative_to(repo)} is out of date: run scripts/gen-oled-web-font.py')
    print('PASS OLED web font matches oled_font.h')
else:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(output, encoding='utf-8', newline='\n')
