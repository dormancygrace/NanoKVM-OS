#!/usr/bin/env python3
"""Generate the SHA-256 or SHA-512 compression function for the T-Head C906.

    void NAME(uintN_t state[8], const uint8_t *in, size_t blocks);

state holds the eight chaining words in host order; in may have any alignment;
blocks may be 0. Scalar code with XTheadBb (th.srri, th.srriw, th.rev,
th.revw).

The C906 has a 32 KiB instruction cache and no L2 cache, so the function is
kept small instead of unrolling all rounds: rounds 0 to 15 once, then one body
of 16 rounds for the message schedule, run 3 times (SHA-256) or 4 times
(SHA-512). Within a body the registers of the eight working variables rotate
by renaming. The schedule keeps w[i-1], w[i-2] and w[i-16] in registers and
the sixteen-word window on the stack; a round takes 26 instructions without
the schedule and 39 with it. The window is wiped before return.

The generator runs what it emits against hashlib (--selftest) with an
interpreter of the instructions it uses.

Usage: gen_sha2_c906.py --bits 256|512 --name NAME [--flavor openssl|plain]
       (--output FILE | --check PATCH PATH) [--selftest CASES]
"""
