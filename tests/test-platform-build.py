#!/usr/bin/env python3
"""Check platform output hashes, toolchain inputs and package payload assembly."""

import hashlib
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

REPO = Path(__file__).resolve().parents[1]


def build(tree, out, *steps):
    return subprocess.run(["bash", str(tree / "platform/build.sh"), "-o", str(out), *steps],
                          capture_output=True, text=True)


def expect(result, success, name, text=None):
    assert (result.returncode == 0) == success, (name, result.stdout, result.stderr)
    if text is not None:
        assert text in result.stdout + result.stderr, (name, text, result.stdout, result.stderr)
    print(f"{name}: pass")


with tempfile.TemporaryDirectory(prefix="nkos-platform-") as directory:
    root = Path(directory)
    # A minimal checkout: build.sh and its lists, the release name and a
    # stand-in for firmware/buildroot.
    tree = root / "repo"
    shutil.copytree(REPO / "platform", tree / "platform",
                    ignore=shutil.ignore_patterns("*.patch", "*.bin", "hwcrypto"))
    (tree / "scripts").mkdir()
    shutil.copy(REPO / "scripts/nanokvm_cpu_profile.py", tree / "scripts/")
    (tree / "firmware/alpine").mkdir(parents=True)
    shutil.copy(REPO / "firmware/alpine/release.env", tree / "firmware/alpine/release.env")
    defconfig = tree / "firmware/buildroot/configs/nanokvm_platform_defconfig"
    defconfig.parent.mkdir(parents=True)
    defconfig.write_text("BR2_riscv=y\n")
    out = root / "out"
    images = out / "images"

    images.mkdir(parents=True)
    expect(build(tree, out, "hashes"), False, "empty output tree is rejected", "No build outputs")
    (images / "SHA256SUMS").write_text("old manifest\n")
    expect(build(tree, out, "hashes"), False, "manifest alone is not a build", "No build outputs")

    outputs = {"Image": b"kernel", "u-boot.bin": b"loader", "boot/alpha.sd": b"fit"}
    for name, data in outputs.items():
        (images / name).parent.mkdir(parents=True, exist_ok=True)
        (images / name).write_bytes(data)
    listed = "".join(f"{hashlib.sha256(outputs[name]).hexdigest()}  {name}\n" for name in sorted(outputs))
    expect(build(tree, out, "hashes"), True, "hashes of every output", "3 outputs")
    assert (images / "SHA256SUMS").read_text() == listed, (images / "SHA256SUMS").read_text()
    expect(build(tree, out, "hashes"), True, "hashes leave out their own SHA256SUMS", "3 outputs")
    assert (images / "SHA256SUMS").read_text() == listed
    (images / "fip.bin").write_bytes(b"new")
    expect(build(tree, out, "hashes"), True, "a new output is listed", "4 outputs")
    assert "fip.bin" in (images / "SHA256SUMS").read_text()
    (images / "fip.bin").unlink()

    # The toolchain is reused only if it was built from the current inputs.
    stamp = out / "buildroot-output/.platform-toolchain"
    stamp.parent.mkdir(parents=True)
    stamp.write_text("previous inputs\n")
    result = build(tree, out, "toolchain")
    expect(result, False, "toolchain from other inputs is rejected", "Delete")
    current = re.search(r"current:\s+([0-9a-f]{64})", result.stderr).group(1)
    stamp.write_text(current + "\n")
    expect(build(tree, out, "toolchain"), True, "unchanged inputs reuse the toolchain", "already built")
    defconfig.write_text("BR2_riscv=y\nBR2_CCACHE=y\n")
    expect(build(tree, out, "toolchain"), False, "changed Buildroot configuration is rejected", current)
    defconfig.write_text("BR2_riscv=y\n")
    lock = tree / "platform/sources.lock"
    original = lock.read_text()
    lock.write_text(re.sub(r"(?m)^(buildroot\s+\S+\s+)\S+", r"\g<1>" + "0" * 64, original))
    expect(build(tree, out, "toolchain"), False, "changed Buildroot archive pin is rejected")
    lock.write_text(original)
    expect(build(tree, out, "toolchain"), True, "restored inputs reuse the toolchain again")

    # An interrupted build from other inputs is not continued either.
    stamp.unlink()
    (out / "buildroot").mkdir()
    (out / "buildroot/.platform-patched").write_text("previous inputs\n")
    expect(build(tree, out, "toolchain"), False, "interrupted build from other inputs is rejected", "Delete")

    # Assemble the real primary manifest, using repository files unchanged and
    # stand-ins only for cross-built outputs. Legacy staging scripts are not
    # involved, so a missing primary manifest entry cannot be hidden by them.
    for line in (tree / "platform/packages.list").read_text().splitlines():
        fields = line.split()
        if not fields or fields[0].startswith("#") or fields[1] not in ("file", "tree"):
            continue
        _, kind, _, _, name = fields
        if name.startswith("%"):
            continue  # Generated by the real payloads step.
        if name.startswith("@"):
            destination = images / name[1:]
            if kind == "tree":
                destination = destination / "fixture"
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(b"cross-built fixture\n")
        else:
            destination = tree / name
            destination.parent.mkdir(parents=True, exist_ok=True)
            if kind == "tree":
                shutil.copytree(REPO / name, destination, dirs_exist_ok=True)
            else:
                shutil.copyfile(REPO / name, destination)
    host_python = out / "buildroot-output/host/bin/python3"
    host_python.parent.mkdir(parents=True, exist_ok=True)
    host_python.symlink_to(sys.executable)
    # A previous debug invocation must not become a release package merely
    # because the next shell omitted NANOKVM_KERNEL_PROFILE.
    release_metadata = images / "boot/kernel.release"
    saved_metadata = release_metadata.read_bytes() if release_metadata.exists() else None
    release_metadata.write_text("7.3.0-nanokvm-os-r5-debug\n")
    expect(build(tree, out, "payloads"), False, "debug artifacts reject release payloads", "Output kernel profile is debug")
    assert not (out / "payloads").exists(), "profile mismatch mutated payloads"
    if saved_metadata is None:
        release_metadata.unlink()
    else:
        release_metadata.write_bytes(saved_metadata)
    marker = out / ".kernel-profile"
    marker.write_text("debug\n")
    for step in ("kernel", "modules", "initramfs", "boot", "payloads", "stock-installer"):
        expect(build(tree, out, step), False, f"persisted debug profile rejects release {step}", "Output kernel profile is debug")
    marker.unlink()
    expect(build(tree, out, "payloads"), True, "primary package payload assembly")
    assert marker.read_text() == "release\n"
    debug_env = dict(os.environ, NANOKVM_KERNEL_PROFILE="debug")
    result = subprocess.run(["bash", str(tree / "platform/build.sh"), "-o", str(out), "kernel"],
                            env=debug_env, capture_output=True, text=True)
    expect(result, False, "release artifacts reject debug rebuild", "Output kernel profile is release")
    for step in ("payloads", "packages", "rootfs", "image", "stock-installer"):
        result = subprocess.run(["bash", str(tree / "platform/build.sh"), "-o", str(root / "debug"), step],
                                env=debug_env, capture_output=True, text=True)
        expect(result, False, f"debug {step} needs test keys", "need -d (test keys)")
    # -e already excludes -d, so a debug package can only carry test keys.
    result = subprocess.run(["bash", str(tree / "platform/build.sh"), "-o", str(root / "debug"),
                             "-e", __file__, "-d", "packages"],
                            env=debug_env, capture_output=True, text=True)
    expect(result, False, "debug packages refuse release keys", "-e, -d and -u exclude each other")
