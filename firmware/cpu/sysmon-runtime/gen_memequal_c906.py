#!/usr/bin/env python3
"""Generate bytealg_memequal_riscv64.s, the XTheadVector loop of runtime.memequal.

prepare.py installs it in internal/bytealg as nanokvm_memequal_riscv64.s and makes
memequal (bytes.Equal, string and array comparisons) jump here for at least
nanokvmVectorMemequalMin bytes unless built with nanokvmqemu (see
bytealg_xtheadvector_riscv64.go). Go's own vector path needs RVV 1.0, which the C906
lacks. Vector instructions are WORDs, encoded and checked against GNU as/objdump by
the encoder of ../go-crypto-c906/gen_chacha_riscv64.py.

Usage: gen_memequal_c906.py --binutils PREFIX (--output FILE | --check FILE)
"""
from pathlib import Path
import argparse, sys

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'go-crypto-c906'))
from gen_chacha_riscv64 import ABI, Asm, OPIVV, OPMVV, V, opv, vsetvli, vle, verify  # noqa: E402

# Go register numbers. memequal's arguments arrive in X10-X12 (ABIInternal);
# the result goes back in X10.
A, B, N = 10, 11, 12
VL, DIFF = 13, 14
LMUL = 4  # 64 bytes per load at VLEN 128, as in gen_memmove_c906.py


def vmsne_vv(vd, vs2, vs1):
    return V(f'th.vmsne.vv v{vd},v{vs2},v{vs1}', opv(0b011001, 1, vs2, vs1, OPIVV, vd))


def vmpopc(rd, vs2):
    # 0.7.1 vmpopc.m: funct6 010100, OPMVV, vs1 = 0, scalar destination.
    return V(f'th.vmpopc.m {ABI[rd]},v{vs2}', opv(0b010100, 1, vs2, 0, OPMVV, rd))


def build():
    a = Asm()
    a('TEXT runtime·nanokvmMemequalVector(SB),NOSPLIT|NOFRAME,$0')
    a('// X10 = a, X11 = b, X12 = size; size >= nanokvmVectorMemequalMin.')
    a('// Byte elements, so neither pointer needs any alignment.')
    a.label('loop')
    a(vsetvli(VL, N, 8, LMUL), vle(8, A), vle(16, B), vmsne_vv(0, 8, 16), vmpopc(DIFF, 0))
    a(f'BNEZ\tX{DIFF}, differ')
    a(f'ADD\tX{VL}, X{A}', f'ADD\tX{VL}, X{B}', f'SUB\tX{VL}, X{N}', f'BNEZ\tX{N}, loop')
    a(f'MOV\t$1, X{A}', 'RET')
    a.label('differ')
    a(f'MOV\tZERO, X{A}', 'RET')
    return a


HEADER = '''// Code generated by gen_memequal_c906.py; DO NOT EDIT.

// Copyright 2026 NanoKVM OS contributors.
// Use of this source code is governed by a BSD-style license matching Go.

// runtime.memequal's loop for XTheadVector (T-Head C906, VLEN 128): two
// unit-stride loads of LMUL 4 register groups, 64 bytes each, compared into
// a mask whose set bits are counted. Go's own vector loop is RVV 1.0.
//
// Vector registers are not preserved across calls; this code calls nothing.
// Assembly functions are not asynchronously preempted; the kernel saves
// vector state across context switches and signals.
//
// Go's assembler has no RVV 0.7.1 encodings, so vector instructions are WORDs.
// The generator checks each against GNU as/objdump -march=rv64gc_xtheadvector.

#include "textflag.h"

'''


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--binutils', required=True, help='GNU binutils prefix with XTheadVector support')
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument('--output', type=Path)
    g.add_argument('--check', type=Path)
    args = p.parse_args()
    a = build()
    n = verify(args.binutils, a.vectors)
    text = HEADER + a.render()
    if args.check:
        if args.check.read_text() != text:
            sys.exit(f'{args.check} is not up to date')
        print(f'{args.check}: up to date, {n} distinct vector encodings verified')
    else:
        args.output.write_text(text)
        print(f'{args.output}: {len(a.vectors)} vector instructions, {n} distinct encodings verified')


if __name__ == '__main__':
    main()
