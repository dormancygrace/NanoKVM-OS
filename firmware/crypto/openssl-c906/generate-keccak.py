#!/usr/bin/env python3
"""Keccak-f[1600] and SHA3_absorb for the C906 from CRYPTOGAMS keccak1600-riscv.pl (pinned commit).

The C906 has no Zbb (no andn, no rori), so the no-Zbb path is taken: all 25 lanes in registers, lane complementing
instead of andn. XTheadBb has th.srri, so each shift/shift/or rotate of the round becomes one th.srri, with the data
flow and liveness of every temporary checked. The output is preprocessed assembly with no conditionals left: the
misaligned-fast input path, no Zicfilp landing pads. SHA3_squeeze is left out (OpenSSL's takes a `next` argument the
CRYPTOGAMS one lacks; keccak1600_c906.c provides it on top of the permutation), and KeccakF1600 becomes the hidden
ossl_keccakf1600_c906.

  generate-keccak.py --print-url
  generate-keccak.py --cryptogams keccak1600-riscv.pl [--binutils PREFIX] (--output FILE | --check)
"""
import argparse
import hashlib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

COMMIT = '4acc4a308eab6049d1cf1c7ba61b353a36ce0e2d'
SHA256 = '4b3d783ff0c651b00ac32eb13decc1f4c054d457f143f477be3f0f944718dcc5'
URL = f'https://raw.githubusercontent.com/dot-asm/cryptogams/{COMMIT}/riscv/keccak1600-riscv.pl'
PATCH = Path(__file__).parent / '0013-keccak-c906.patch'
NAME = 'crypto/sha/keccak1600-c906.S'

ALLOWED = {'xor', 'or', 'and', 'not', 'ld', 'sd', 'add', 'addi', 'bne', 'th.srri', 'ret', 'lla', 'slli', 'mv'}

HEADER = f'''/* SPDX-License-Identifier: GPL-1.0+ OR BSD-3-Clause */
/*
 * Generated by firmware/crypto/openssl-c906/generate-keccak.py from CRYPTOGAMS keccak1600-riscv.pl by Andy Polyakov
 * (@dot-asm), commit {COMMIT[:12]}. Do not edit.
 *
 * No-Zbb lane-complementing round with its rotates fused into XTheadBb th.srri (FUSED of them); KeccakF1600
 * renamed ossl_keccakf1600_c906 (hidden); SHA3_squeeze left to keccak1600_c906.c.
 */
'''


def preprocess(perl, cc):
    """Run the perlasm and the C preprocessor for the no-Zbb, fast-misaligned path."""
    with tempfile.TemporaryDirectory() as tmp:
        s = Path(tmp) / 'keccak.S'
        subprocess.run(['perl', str(perl), '64', str(s)], check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        out = subprocess.run([cc, '-E', '-P', '-undef', '-x', 'assembler-with-cpp',
                              '-D__riscv', '-D__riscv_xlen=64', '-D__SIZEOF_POINTER__=8',
                              '-D__riscv_misaligned_fast', str(s)],
                             check=True, capture_output=True, text=True).stdout
    return out.splitlines()


def parse(lines):
    """Return [('label', name)] / [(op, [args])] with comments stripped."""
    out = []
    for line in lines:
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        if line.endswith(':'):
            out.append(('label', line[:-1]))
            continue
        op, _, rest = line.partition(' ')
        args = [a.strip() for a in rest.split(',')] if rest.strip() else []
        out.append((op.strip(), args))
    return out


def imm(text):
    return int(eval(text, {}, {}))  # CRYPTOGAMS writes immediates such as 64-44


def writes(ins):
    op, a = ins
    if op in ('sd', 'bne', 'label', 'ret'):
        return None
    return a[0] if a else None


def reads(ins):
    op, a = ins
    if op == 'label':
        return set()
    if op == 'sd':
        return {a[0], a[1].split('(')[1].rstrip(')')}
    if op == 'ld':
        return {a[1].split('(')[1].rstrip(')')}
    if op == 'bne':
        return {a[0], a[1]}
    return {x for x in a[1:] if re.fullmatch(r'x\d+', x)}


def dead_after(code, idx, reg):
    """True if reg is written before it is read after code[idx] (to the loop end)."""
    for ins in code[idx + 1:]:
        if ins[0] == 'label':
            continue
        if reg in reads(ins):
            return False
        if writes(ins) == reg:
            return True
    return False


def fuse_rotl1_xor(code):
    """Theta: add T,S,S / xor D,D,X / srl U,S,63 / xor D,D,U  ->  th.srri V,S,63 / xor D,D,X'.

    Two layouts occur: the shifted halves are XORed into D one after the
    other, either with the left half in a temporary (A == T, X == T) or in D
    itself (A == D). The rotate result goes to the register that held the
    left half; the srl temporary must be dead afterwards.
    """
    code = list(code)
    fused = 0
    k = 0
    while k + 3 < len(code):
        (o1, a1), (o2, a2), (o3, a3), (o4, a4) = code[k:k + 4]
        if (o1 == 'add' and a1[1] == a1[2] and o2 == 'xor' and o3 in ('srl', 'srli')
                and imm(a3[2]) == 63 and a3[1] == a1[1] and o4 == 'xor' and a4[2] == a3[0]
                and a4[0] == a4[1] == a2[0] == a2[1]):
            left, src, d, x, u = a1[0], a1[1], a2[0], a2[2], a3[0]
            if left == x and left != d:
                # T = S<<1; D ^= T; U = S>>63; D ^= U   ->  T = rotl(S,1); D ^= T
                new = [('th.srri', [left, src, '63']), ('xor', [d, d, left])]
                changed = {u} - {left}
            elif left == d:
                # D = S<<1; D ^= X; U = S>>63; D ^= U   ->  D = rotl(S,1); D ^= X
                if x == src:
                    k += 1
                    continue
                new = [('th.srri', [d, src, '63']), ('xor', [d, d, x])]
                changed = {u}
            else:
                k += 1
                continue
            for reg in changed:
                if not dead_after(code, k + 3, reg):
                    sys.exit(f'rotl1 temporary {reg} is live after {code[k:k + 4]}')
            code[k:k + 4] = new
            fused += 1
        k += 1
    return code, fused


def fuse_rotates(code):
    """Replace sll/add + srl + or rotate idioms by th.srri, verifying data flow."""
    code, fused = fuse_rotl1_xor(code)
    code = list(code)
    i = 0
    while i < len(code):
        op, a = code[i]
        if op != 'or' or a[0] != a[1]:
            i += 1
            continue
        d, t = a[0], a[2]
        # Find the shift-left (sll d, s, r or add d, s, s) and srl t, s, 64-r before i.
        left = right = None
        for j in range(i - 1, max(-1, i - 40), -1):
            pj, aj = code[j]
            if left is None and writes(code[j]) == d:
                if pj in ('sll', 'slli'):
                    left = (j, aj[1], imm(aj[2]))
                elif pj == 'add' and aj[1] == aj[2]:
                    left = (j, aj[1], 1)
                else:
                    break
            if right is None and writes(code[j]) == t:
                if pj in ('srl', 'srli'):
                    right = (j, aj[1], imm(aj[2]))
                else:
                    break
            if left and right:
                break
        if not (left and right) or left[1] != right[1] or left[2] + right[2] != 64:
            i += 1
            continue
        (jl, src, r), (jr, _, _) = left, right
        lo, hi = min(jl, jr), max(jl, jr)
        # Source must keep its value between the two shifts, except when the
        # srl itself overwrites it last (t == src, the srl after the sll).
        ok = True
        for k in range(lo + 1, i):
            if k in (jl, jr):
                continue
            w, rd = writes(code[k]), reads(code[k])
            if w in (d, t) or (k < hi and w == src) or d in rd or t in rd:
                ok = False
                break
        if t == src and jr < jl:
            ok = False  # srl clobbered the source before the sll read it
        if not ok:
            sys.exit(f'unsafe rotate pattern at {code[i]}')
        # Without the srl, t keeps its old value (the unshifted source when
        # t == src); that is only safe if t is dead after the or.
        if t != d and not dead_after(code, i, t):
            sys.exit(f'rotate temporary {t} is live after {code[i]}')
        code[jl] = ('th.srri', [d, src, str(64 - r)])
        for k in sorted((jr, i), reverse=True):
            del code[k]
        fused += 1
        i = jl + 1
    return code, fused




def generate(perl, cc, binutils=None):
    lines = preprocess(perl, cc)
    # The round function, from its label to its .size, with its rotates fused.
    a = next(i for i, l in enumerate(lines) if l.startswith('__KeccakF1600:'))
    b = next(i for i, l in enumerate(lines) if re.match(r'\s*\.size\s+__KeccakF1600', l))
    core = parse(lines[a + 1:b])
    core, fused = fuse_rotates(core)
    bad = {op for op, _ in core if op != 'label' and not op.startswith('.') and op not in ALLOWED}
    if bad:
        sys.exit(f'unexpected instructions in the round after fusion: {sorted(bad)}')
    if fused < 29:
        sys.exit(f'only {fused} rotates fused; unexpected CRYPTOGAMS source')
    body = []
    for op, args in core:
        if op == 'label':
            body.append(f'{args}:')
        else:
            body.append(f'\t{op}\t' + ', '.join(args) if args else f'\t{op}')
    text = '\n'.join(lines[:a + 1] + body + lines[b:]) + '\n'
    # SHA3_squeeze out; KeccakF1600 renamed, global but hidden, for keccak1600_c906.c.
    m = re.search(r'\n[ \t]*\.globl[ \t]+SHA3_squeeze\n.*?\.size[ \t]+SHA3_squeeze,[^\n]*\n', text, re.S)
    if not m:
        sys.exit('SHA3_squeeze not found')
    text = text[:m.start()] + '\n' + text[m.end():]
    text = re.sub(r'\bKeccakF1600\b', 'ossl_keccakf1600_c906', text)
    text, n = re.subn(r'(\n[ \t]*)(\.type[ \t]+ossl_keccakf1600_c906)',
                      r'\1.globl\tossl_keccakf1600_c906\1.hidden\tossl_keccakf1600_c906\1\2', text, count=1)
    if n != 1 or 'SHA3_absorb' not in text:
        sys.exit('unexpected CRYPTOGAMS source layout')
    if re.search(r'\b(rori|andn|lpad)\b', text):
        sys.exit('Zbb or Zicfilp instructions left')
    out = HEADER.replace('FUSED', str(fused)) + text + '.section .note.GNU-stack,"",@progbits\n'
    if binutils:
        check_assembles(out, binutils)
    return out, fused


def check_assembles(text, binutils):
    """Assemble the file for rv64gc_xtheadbb: every th.srri must come out as one."""
    with tempfile.TemporaryDirectory() as tmp:
        src, obj = Path(tmp) / 'k.S', Path(tmp) / 'k.o'
        src.write_text(text)
        subprocess.run([binutils + 'gcc', '-c', '-march=rv64gc_xtheadbb', '-mabi=lp64d', '-o', str(obj), str(src)],
                       check=True)
        dump = subprocess.run([binutils + 'objdump', '-d', str(obj)], check=True, capture_output=True,
                              text=True).stdout
    if len(re.findall(r'\bth\.srri\b', dump)) != len(re.findall(r'^\tth\.srri\b', text, re.M)):
        sys.exit('th.srri count differs after assembling')


def from_patch():
    lines = PATCH.read_text().splitlines(keepends=True)
    start = next(i for i, l in enumerate(lines) if l == f'+++ b/{NAME}\n')
    added = []
    for line in lines[start + 2:]:
        if line.startswith(('diff --git', '--- ')):
            break
        if line.startswith('+'):
            added.append(line[1:])
    return ''.join(added)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--print-url', action='store_true')
    p.add_argument('--cryptogams', type=Path)
    p.add_argument('--cc', default='cpp')
    p.add_argument('--binutils', help='riscv64 toolchain prefix: assemble the output and count th.srri')
    p.add_argument('--output', type=Path)
    p.add_argument('--check', action='store_true', help='compare with the file in the patch')
    a = p.parse_args()
    if a.print_url:
        print(URL)
        return
    if not a.cryptogams:
        p.error('--cryptogams is required')
    digest = hashlib.sha256(a.cryptogams.read_bytes()).hexdigest()
    if digest != SHA256:
        sys.exit(f'{a.cryptogams}: sha256 {digest}, pinned {SHA256} (commit {COMMIT})')
    text, fused = generate(a.cryptogams, a.cc, a.binutils)
    print(f'fused {fused} rotates', file=sys.stderr)
    if a.output:
        a.output.write_text(text)
    if a.check:
        if from_patch() != text:
            sys.exit(f'{NAME} in {PATCH.name} is stale; regenerate it')
        print('check: up to date', file=sys.stderr)


if __name__ == '__main__':
    main()
