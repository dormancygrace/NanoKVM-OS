// Alpine's udhcpc script (/usr/share/udhcpc/default.script from busybox) runs
// the executables in /etc/udhcpc/post-<event>/ after each event, without
// arguments; the hooks take the event from their directory. The Buildroot
// script ran /usr/share/udhcpc/default.script.d/ instead, which Alpine never
// reads.
var (
	udhcpcHookDirs   = []string{"/etc/udhcpc/post-bound", "/etc/udhcpc/post-renew"}
	legacyHookDir    = "/usr/share/udhcpc/default.script.d"
	udhcpcConfFile   = "/etc/udhcpc/udhcpc.conf"
	resolvconfRunner = runResolvconf
)

// udhcpc's script must leave /etc/resolv.conf to openresolv. The base DNS,
// manual servers and VPN DNS are layered there, and a direct write makes every
// later resolvconf call fail with "signature mismatch".
const udhcpcResolvLine = `RESOLV_CONF="no" # NanoKVM: openresolv owns /etc/resolv.conf`

func installUDHCPCHook(name, script string) error {
	for _, dir := range udhcpcHookDirs {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return fmt.Errorf("create DHCP hook directory: %w", err)
		}
		if err := os.WriteFile(filepath.Join(dir, name), []byte(script), 0o755); err != nil {
			return fmt.Errorf("install DHCP hook %s: %w", name, err)
		}
	}
	if err := os.Remove(filepath.Join(legacyHookDir, name)); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("remove legacy DHCP hook %s: %w", name, err)
	}
	return nil
}

func ensureUDHCPCLeavesResolvConf() error {
	data, err := os.ReadFile(udhcpcConfFile)
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("read udhcpc configuration: %w", err)
	}
	for _, line := range strings.Split(string(data), "\n") {
		if strings.TrimSpace(line) == udhcpcResolvLine {
			return nil
		}
	}
	text := string(data)
	if text != "" && !strings.HasSuffix(text, "\n") {
		text += "\n"
	}
	if err := os.MkdirAll(filepath.Dir(udhcpcConfFile), 0o755); err != nil {
		return fmt.Errorf("create udhcpc configuration directory: %w", err)
	}
	if err := os.WriteFile(udhcpcConfFile, []byte(text+udhcpcResolvLine+"\n"), 0o644); err != nil {
		return fmt.Errorf("write udhcpc configuration: %w", err)
	}
	return nil
}

func runResolvconf(tool, input string, args ...string) error {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, tool, args...)
	cmd.Stdin = strings.NewReader(input)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("%w: %s", err, strings.TrimSpace(stderr.String()))
	}
	return nil
}

// publishBaseResolver hands the base DNS to openresolv. If /etc/resolv.conf
// was written past it (by udhcpc before it was told not to), openresolv
// refuses with "signature mismatch" until it takes the file over again.
func publishBaseResolver(tool, content string) error {
	err := resolvconfRunner(tool, content, "-a", "nkos.base")
	if err == nil || !strings.Contains(err.Error(), "signature mismatch") {
		return err
	}
	if err := resolvconfRunner(tool, "", "-u"); err != nil {
		return fmt.Errorf("take over /etc/resolv.conf: %w", err)
	}
	return resolvconfRunner(tool, content, "-a", "nkos.base")
}

// EnsureDHCPIntegration runs at startup. It installs the DHCP hooks where
// Alpine runs them, stops udhcpc from writing /etc/resolv.conf, and hands a
// file it wrote earlier back to openresolv with the current base DNS.
func EnsureDHCPIntegration() error {
	var errs []error
	if err := installUDHCPCHook(udhcpcDNSHookName, udhcpcDNSHook); err != nil {
		errs = append(errs, err)
	}
	if err := installUDHCPCHook(udhcpcGatewayHookName, udhcpcGatewayHook); err != nil {
		errs = append(errs, err)
	}
	if err := ensureUDHCPCLeavesResolvConf(); err != nil {
		errs = append(errs, err)
	}
	if err := adoptResolvConf(); err != nil {
		errs = append(errs, err)
	}
	return errors.Join(errs...)
}

func adoptResolvConf() error {
	tool, err := exec.LookPath("resolvconf")
	if err != nil {
		return nil
	}
	data, err := os.ReadFile(etcResolvFile)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return fmt.Errorf("read %s: %w", etcResolvFile, err)
	}
	if strings.Contains(string(data), "# Generated by resolvconf") {
		return nil
	}
	base := string(data)
	if currentDNSMode() == dnsModeManual {
		if servers := readManualDNSServers(); len(servers) > 0 {
			base = "nameserver " + strings.Join(servers, "\nnameserver ") + "\n"
		}
	} else if err := refreshDHCPResolvCacheFromEffective(); err != nil {
		log.Warnf("failed to cache dhcp dns before handing resolv.conf to openresolv: %s", err)
	}
	if err := adoptBaseResolver(tool, base); err != nil {
		return err
	}
	log.Infof("handed %s to openresolv", etcResolvFile)
	return nil
}

// Adopt even an empty resolver before DHCP has supplied a nameserver. Otherwise
// openresolv rejects every later DHCP update with "signature mismatch". Keep
// existing DHCP/VPN entries when the file is empty or only has comments. If
// it has other resolver settings, preserve those without replacing DNS servers
// already submitted under nkos.base.
func adoptBaseResolver(tool, base string) error {
	hasSettings, hasServers := false, false
	for _, line := range strings.Split(base, "\n") {
		line, _, _ = strings.Cut(line, "#")
		line, _, _ = strings.Cut(line, ";")
		fields := strings.Fields(line)
		if len(fields) > 1 {
			hasSettings = true
			hasServers = hasServers || fields[0] == "nameserver"
		}
	}
	if hasSettings && !hasServers {
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		previous, err := exec.CommandContext(ctx, tool, "-l", "nkos.base").Output()
		var exitErr *exec.ExitError
		// openresolv returns 2 when the requested key does not exist yet.
		if err != nil && !(errors.As(err, &exitErr) && exitErr.ExitCode() == 2) {
			return fmt.Errorf("read existing base dns: %w", err)
		}
		base = string(previous) + "\n" + base
	}
	if err := resolvconfRunner(tool, "", "-u"); err != nil {
		return fmt.Errorf("take over %s: %w", etcResolvFile, err)
	}
	if hasSettings {
		if err := resolvconfRunner(tool, base, "-a", "nkos.base"); err != nil {
			return fmt.Errorf("publish base dns: %w", err)
		}
	}
	return nil
}

// DHCPv6 publishes per-link entries alongside nkos.base. Manual DNS must
// withdraw those automatic entries without removing a VPN's resolver.
func clearDHCPv6Resolvers() error {
	tool, err := exec.LookPath("resolvconf")
	if err != nil {
		return nil
	}
	for _, name := range ipv6Interfaces {
		if err := resolvconfRunner(tool, "", "-d", "nkos.dhcpv6."+name, "-f"); err != nil {
			return fmt.Errorf("remove DHCPv6 DNS for %s: %w", name, err)
		}
	}
	return nil
}
