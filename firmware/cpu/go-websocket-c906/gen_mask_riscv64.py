#!/usr/bin/env python3
"""Generate the measured C906 WebSocket mask and verify XTheadVector words."""
import argparse
import importlib.util
from pathlib import Path

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("c906_encoder", HERE.parent / "go-crypto-c906/gen_chacha_riscv64.py")
V = importlib.util.module_from_spec(spec)
spec.loader.exec_module(V)

HEADER = """// Code generated by gen_mask_riscv64.py. DO NOT EDIT.
// Copyright 2026 NanoKVM OS contributors.
// Use of this source code is governed by the BSD-style LICENSE in this directory.

//go:build gc && !purego && !appengine

// SG2002/C906: scalar words for 8–127B, byte-vector groups from 128B.
// All accesses stay inside the input slice. The repeated 32-bit mask is
// rotated by pos before either path; full vector groups advance by a
// multiple of four bytes. Only the final vector operation may shorten VL.
// No calls or safepoints occur while vector state is live. Linux saves it
// across signals and task switches.

#include "textflag.h"

"""

def build():
    a = V.Asm()
    a('TEXT ·maskBytesC906(SB), NOSPLIT, $0-48')
    a('MOVWU key+0(FP), X12')
    a('MOV pos+8(FP), X13')
    a('MOV b_base+16(FP), X10')
    a('MOV b_len+24(FP), X11')
    a('ADD X11, X13, X14')
    a('AND $3, X14')
    a('MOV X14, ret+40(FP)')
    a('BEQZ X11, done')
    a('SLL $32, X12, X14')
    a('OR X14, X12')
    a('AND $3, X13')
    a('SLL $3, X13')
    a('NEG X13, X14')
    a('SRL X13, X12, X15')
    a('SLL X14, X12, X16')
    a('OR X16, X15, X12')
    a('MOV $128, X9')
    a('BLT X11, X9, scalar')
    a('MOV $32, X5')
    a(V.vsetvli(6,5,32,8))
    a(V.vmv_v_x(0,12))
    a('MOV $128, X5')
    a(V.vsetvli(6,5,8,8))
    a.label('vector_loop')
    a(V.vle(8,10))
    a(V.vv('vxor',8,8,0))
    a(V.vse(8,10))
    a('ADD X6, X10')
    a('SUB X6, X11')
    a('BGE X11, X6, vector_loop')
    a('BEQZ X11, done')
    a(V.vsetvli(5,11,8,8))
    a(V.vle(8,10))
    a(V.vv('vxor',8,8,0))
    a(V.vse(8,10))
    a('RET')
    a.label('scalar')
    a('MOV $64, X9')
    a('BLT X11, X9, words')
    a.label('loop64')
    a('MOV 0(X10), X5')
    a('MOV 8(X10), X6')
    a('MOV 16(X10), X7')
    a('MOV 24(X10), X8')
    a('MOV 32(X10), X14')
    a('MOV 40(X10), X15')
    a('MOV 48(X10), X16')
    a('MOV 56(X10), X17')
    a('XOR X12, X5')
    a('XOR X12, X6')
    a('XOR X12, X7')
    a('XOR X12, X8')
    a('XOR X12, X14')
    a('XOR X12, X15')
    a('XOR X12, X16')
    a('XOR X12, X17')
    a('MOV X5, 0(X10)')
    a('MOV X6, 8(X10)')
    a('MOV X7, 16(X10)')
    a('MOV X8, 24(X10)')
    a('MOV X14, 32(X10)')
    a('MOV X15, 40(X10)')
    a('MOV X16, 48(X10)')
    a('MOV X17, 56(X10)')
    a('ADD $64, X10')
    a('SUB $64, X11')
    a('BGE X11, X9, loop64')
    a.label('words')
    a('MOV $8, X9')
    a('BLT X11, X9, tail')
    a.label('word_loop')
    a('MOV 0(X10), X5')
    a('XOR X12, X5')
    a('MOV X5, 0(X10)')
    a('ADD $8, X10')
    a('SUB $8, X11')
    a('BGE X11, X9, word_loop')
    a.label('tail')
    a('BEQZ X11, done')
    a.label('byte_loop')
    a('MOVBU 0(X10), X5')
    a('XOR X12, X5')
    a('MOVB X5, 0(X10)')
    a('SRL $8, X12')
    a('ADD $1, X10')
    a('SUB $1, X11')
    a('BNEZ X11, byte_loop')
    a.label('done')
    a('RET')
    return a

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binutils", required=True)
    target = parser.add_mutually_exclusive_group(required=True)
    target.add_argument("--output", type=Path)
    target.add_argument("--check", type=Path)
    args = parser.parse_args()
    asm = build()
    count = V.verify(args.binutils, asm.vectors)
    text = HEADER + asm.render()
    if args.check:
        if args.check.read_text() != text:
            parser.error(f"{args.check} is not up to date")
    else:
        args.output.write_text(text)
    print(f"{args.check or args.output}: {count} distinct vector encodings verified")

if __name__ == "__main__":
    main()
