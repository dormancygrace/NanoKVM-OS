#!/usr/bin/env python3
"""Scalar ChaCha20 for the C906 from CRYPTOGAMS chacha-riscv.pl (pinned commit).

Mechanical changes only: the Zbb rotations become XTheadBb th.srriw, and the
entry point is renamed ossl_chacha20_ctr32_scalar (hidden). The vector parts of
the file stay behind __riscv_v, which the SG2002 build does not define.

  generate-chacha-scalar.py --print-url
  generate-chacha-scalar.py --cryptogams chacha-riscv.pl (--output FILE | --check)
"""
import argparse
from pathlib import Path
import re
import subprocess
import sys

COMMIT = '4acc4a308eab6049d1cf1c7ba61b353a36ce0e2d'
URL = f'https://raw.githubusercontent.com/dot-asm/cryptogams/{COMMIT}/riscv/chacha-riscv.pl'
PATCH = Path(__file__).parent / '0001-chacha20-c906.patch'
NAME = 'crypto/chacha/chacha-scalar.S'

HEADER = f'''/* SPDX-License-Identifier: GPL-1.0+ OR BSD-3-Clause */
/*
 * Generated by firmware/crypto/openssl-c906/generate-chacha-scalar.py from
 * CRYPTOGAMS chacha-riscv.pl by Andy Polyakov (@dot-asm), commit
 * {COMMIT[:12]}. Do not edit.
 *
 * Zbb rotations replaced by XTheadBb th.srriw; entry point renamed
 * ossl_chacha20_ctr32_scalar. Inputs below three blocks on the C906.
 */
'''


def generate(source):
    raw = subprocess.run(['perl', str(source)], check=True, capture_output=True, text=True).stdout
    text = raw.replace('#ifdef\t__riscv_zbb', '#ifdef\t__riscv_xtheadbb')
    text = re.sub(r'\brorw\b', 'th.srriw', text)
    text = re.sub(r'\bChaCha20_ctr32\b', 'ossl_chacha20_ctr32_scalar', text)
    text = text.replace('.globl\tossl_chacha20_ctr32_scalar\n',
                        '.globl\tossl_chacha20_ctr32_scalar\n.hidden\tossl_chacha20_ctr32_scalar\n')
    if text.count('th.srriw') < 32 or 'rorw' in text:
        sys.exit('unexpected CRYPTOGAMS source: rotations not found')
    return HEADER + text + '\n.section .note.GNU-stack,"",@progbits\n'


def from_patch():
    lines = PATCH.read_text().splitlines(keepends=True)
    start = next(i for i, l in enumerate(lines) if l == f'+++ b/{NAME}\n')
    added = []
    for line in lines[start + 2:]:
        if line.startswith(('diff --git', '--- ')):
            break
        if line.startswith('+'):
            added.append(line[1:])
    return ''.join(added)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--print-url', action='store_true')
    p.add_argument('--cryptogams', type=Path)
    p.add_argument('--output', type=Path)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    if a.print_url:
        print(URL)
        return
    text = generate(a.cryptogams)
    if a.check:
        if from_patch() != text:
            sys.exit(f'{NAME} in {PATCH.name} differs from the generator output')
        print(f'{NAME} matches CRYPTOGAMS {COMMIT[:12]} with XTheadBb rotations')
    else:
        a.output.write_text(text)


if __name__ == '__main__':
    main()
