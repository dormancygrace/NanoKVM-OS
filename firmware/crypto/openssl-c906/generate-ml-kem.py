#!/usr/bin/env python3
"""ML-KEM's NTT, inverse NTT and base-case products for the C906 vector unit, as assembly for OpenSSL.

OpenSSL is built with a CPU profile without the vector extension, and GCC cannot switch XTheadVector on for one
function, so ml-kem-c906.c (RVV intrinsics, which GCC compiles to XTheadVector) is compiled here with the userspace
profile and the assembly goes into the patch as crypto/ml_kem/ml_kem-c906.S, under .option arch, +xtheadvector.
The output is checked: only .text, calls only to its own local functions, the exported symbols hidden, and it
must assemble with OpenSSL's profile.

  generate-ml-kem.py --cross PREFIX (--output FILE | --check)

PREFIX is the riscv64 toolchain prefix (…/riscv64-buildroot-linux-musl-); the output depends on its GCC version.
"""
import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / 'ml-kem-c906.c'
PATCH = HERE / '0014-ml-kem-c906.patch'
NAME = 'crypto/ml_kem/ml_kem-c906.S'
PROFILE = HERE.parents[2] / 'scripts' / 'nanokvm_cpu_profile.py'
EXPORTS = ('ossl_ml_kem_ntt_c906', 'ossl_ml_kem_inverse_ntt_c906', 'ossl_ml_kem_mult_c906')
LOCAL_CALLS = {'layer2', 'layer4'}


def profile(name):
    return subprocess.run([sys.executable, str(PROFILE), name], check=True, capture_output=True, text=True).stdout.split()


def compile_source(gcc):
    flags = [('-O3' if f == '-O2' else f) for f in profile('userspace')]
    version = subprocess.run([gcc, '-dumpfullversion'], check=True, capture_output=True, text=True).stdout.strip()
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / 'ml-kem-c906.s'
        subprocess.run([gcc, *flags, '-fPIC', '-fvisibility=hidden', '-fno-ident', '-S', '-o', str(out), str(SOURCE)],
                       check=True)
        return out.read_text(), version, flags


def check(asm):
    for line in asm.splitlines():
        s = line.strip()
        if s.startswith('.section') and '.note.GNU-stack' not in s:
            sys.exit(f'unexpected section: {s}')
        if s.startswith(('.data', '.rodata', '.bss')):
            sys.exit(f'unexpected section: {s}')
        m = re.match(r'(call|tail)\s+(\S+)', s)
        if m and m.group(2) not in LOCAL_CALLS:
            sys.exit(f'unexpected call: {s}')
        if s.startswith('.globl'):
            sym = s.split()[1]
            if sym not in EXPORTS:
                sys.exit(f'unexpected global: {sym}')
    for sym in EXPORTS:
        if f'.hidden\t{sym}' not in asm and f'.hidden {sym}' not in asm:
            sys.exit(f'{sym} is not hidden')


def generate(cross):
    asm, version, flags = compile_source(cross + 'gcc')
    asm = '\n'.join(l for l in asm.splitlines() if not l.strip().startswith(('.file', '.attribute')))
    check(asm)
    text = f'''/* SPDX-License-Identifier: Apache-2.0 */
/*
 * Generated by firmware/crypto/openssl-c906/generate-ml-kem.py from ml-kem-c906.c (NanoKVM OS) with GCC {version}
 * and the userspace CPU profile. Do not edit.
 *
 * void ossl_ml_kem_ntt_c906(uint16_t c[256], const uint16_t roots[128]);
 * void ossl_ml_kem_inverse_ntt_c906(uint16_t c[256], const uint16_t roots[128], uint16_t inverse_degree);
 * void ossl_ml_kem_mult_c906(uint16_t out[256], const uint16_t lhs[256], const uint16_t rhs[256],
 *                            const uint16_t mod_roots[128], int add);
 *
 * Bit-identical to scalar_ntt, scalar_inverse_ntt, scalar_mult and scalar_mult_add in ml_kem.c. NanoKVM kernel
 * patch 0078 keeps vector state enabled for every user thread.
 */
\t.option\tpush
\t.option\tarch, +xtheadvector
{asm.strip()}
\t.option\tpop
'''
    openssl = [f for f in profile('openssl') if f.startswith(('-march=', '-mabi='))]
    with tempfile.TemporaryDirectory() as tmp:
        s = Path(tmp) / 'ml_kem-c906.S'
        s.write_text(text)
        subprocess.run([cross + 'gcc', *openssl, '-c', '-o', str(Path(tmp) / 'o.o'), str(s)], check=True)
    return text


def from_patch():
    lines = PATCH.read_text().splitlines()
    start = lines.index(f'+++ b/{NAME}') + 2
    out = []
    for line in lines[start:]:
        if line.startswith('diff --git'):
            break
        out.append(line[1:])
    return '\n'.join(out) + '\n'


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--cross', required=True, help='riscv64 toolchain prefix')
    p.add_argument('--output', type=Path)
    p.add_argument('--check', action='store_true', help='compare with the file in the patch')
    a = p.parse_args()
    text = generate(a.cross)
    if a.output:
        a.output.write_text(text)
    if a.check:
        if from_patch() != text:
            sys.exit(f'{NAME} in {PATCH.name} is stale; regenerate it')
        print('check: up to date', file=sys.stderr)


if __name__ == '__main__':
    main()
