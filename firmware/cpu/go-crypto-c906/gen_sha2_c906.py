STATE = ['a3', 'a4', 'a5', 'a6', 'a7', 't0', 't1', 't2']
X, Y, Z = 't4', 't5', 't6'
BC = ['s1', 't3']       # b ^ c of the round, alternating
WREG = ['s2', 's3']     # w[i-2] on entry of a schedule round, w[i] after it, alternating
VREG = ['s4', 's5']     # w[i-16] / w[i-15], alternating
KP, KEND = 's0', 's6'
SAVED = ['s0', 's1', 's2', 's3', 's4', 's5', 's6']

HEAD = '''/* SPDX-License-Identifier: BSD-3-Clause */
/*
 * Generated by firmware/cpu/go-crypto-c906/gen_sha2_c906.py (NanoKVM OS).
 * Do not edit.
 *
 * SHA-%(bits)d compression for the T-Head C906: rounds 0 to 15, then one body
 * of 16 rounds run %(loops)d times; about %(size)d bytes of code. Uses XTheadBb.
 *
 * void %(name)s(uint%(wbits)d_t state[8], const uint8_t *in, size_t blocks);
 *
 * The message schedule on the stack is wiped; s0 to s6 are preserved.
 */
'''


def gen(bits, name, flavor='plain'):
    p = PARAMS[bits]
    wb, rounds = p['wb'], p['rounds']
    frame = (16 * wb + 8 * len(SAVED) + 15) // 16 * 16
    body = []
    e = body.append

    # A loaded value is used no sooner than two instructions later (the C906
    # stalls a cycle otherwise).
    def core(i, st, w, k):
        """One round; w holds w[i], k holds K[i]."""
        a, b, c, d, ee, f, g, h = st
        old, new = BC[i % 2], BC[(i + 1) % 2]
        e('\t%s\t%s, %s, %s' % (p['add'], h, h, w))
        e('\t%s\t%s, %s, %s' % (p['add'], h, h, k))
        e('\t%s\t%s, %s, %d' % (p['ror'], X, ee, p['S1'][0]))
        e('\t%s\t%s, %s, %d' % (p['ror'], Y, ee, p['S1'][1]))
        e('\t%s\t%s, %s, %d' % (p['ror'], Z, ee, p['S1'][2]))
        e('\txor\t%s, %s, %s' % (X, X, Y))
        e('\txor\t%s, %s, %s' % (X, X, Z))
        e('\t%s\t%s, %s, %s' % (p['add'], h, h, X))
        e('\txor\t%s, %s, %s' % (X, f, g))
        e('\tand\t%s, %s, %s' % (X, X, ee))
        e('\txor\t%s, %s, %s' % (X, X, g))
        e('\t%s\t%s, %s, %s' % (p['add'], h, h, X))
        e('\t%s\t%s, %s, %s' % (p['add'], d, d, h))
        e('\t%s\t%s, %s, %d' % (p['ror'], X, a, p['S0'][0]))
        e('\t%s\t%s, %s, %d' % (p['ror'], Y, a, p['S0'][1]))
        e('\t%s\t%s, %s, %d' % (p['ror'], Z, a, p['S0'][2]))
        e('\txor\t%s, %s, %s' % (X, X, Y))
        e('\txor\t%s, %s, %s' % (X, X, Z))
        e('\t%s\t%s, %s, %s' % (p['add'], h, h, X))
        e('\txor\t%s, %s, %s' % (new, a, b))
        e('\tand\t%s, %s, %s' % (Z, new, old))
        e('\txor\t%s, %s, %s' % (Z, Z, b))
        e('\t%s\t%s, %s, %s' % (p['add'], h, h, Z))
        return [h] + st[:7]

    e('\tbeqz\ta2, 9f')
    e('\taddi\tsp, sp, -%d' % frame)
    for k, r in enumerate(SAVED):
        e('\tsd\t%s, %d(sp)' % (r, 16 * wb + 8 * k))
    e('\tslli\ta2, a2, %d' % (6 if bits == 256 else 7))
    e('\tadd\ta2, a1, a2')
    e('\tla\t%s, .L%s_K' % (KP, name))
    e('\taddi\t%s, %s, %d' % (KEND, KP, rounds * wb))
    for k, r in enumerate(STATE):
        e('\t%s\t%s, %d(a0)' % (p['load'], r, k * wb))
    e('\t.p2align 2')
    e('1:')
    st = list(STATE)
    e('\txor\t%s, %s, %s' % (BC[0], st[1], st[2]))
    # rounds 0..15: w[0] stays in VREG[0], w[14] and w[15] in WREG[0] and WREG[1]
    for i in range(16):
        w = VREG[0] if i == 0 else WREG[0] if i == 14 else WREG[1] if i == 15 else X
        e('\t%s\t%s, %d(a1)' % (p['load'], w, i * wb))
        e('\t%s\t%s, %d(%s)' % (p['load'], Y, i * wb, KP))
        e('\t%s\t%s, %s' % (p['rev'], w, w))
        e('\t%s\t%s, %d(sp)' % (p['store'], w, i * wb))
        st = core(i, st, w, Y)
    e('\taddi\t%s, %s, %d' % (KP, KP, 16 * wb))
    e('\t.p2align 2')
    e('2:')
    for i in range(16, 32):
        q = i % 16
        r, vo, vn = WREG[i % 2], VREG[i % 2], VREG[(i + 1) % 2]
        t7 = BC[(i + 1) % 2]    # free until core() writes it
        e('\t%s\t%s, %d(sp)' % (p['load'], vn, ((q + 1) & 15) * wb))
        e('\t%s\t%s, %d(sp)' % (p['load'], t7, ((q + 9) & 15) * wb))
        e('\t%s\t%s, %s, %d' % (p['ror'], X, vn, p['s0'][0]))
        e('\t%s\t%s, %s, %d' % (p['ror'], Y, vn, p['s0'][1]))
        e('\t%s\t%s, %s, %d' % (p['shr'], Z, vn, p['s0'][2]))
        e('\txor\t%s, %s, %s' % (X, X, Y))
        e('\txor\t%s, %s, %s' % (X, X, Z))
        e('\t%s\t%s, %s, %s' % (p['add'], vo, vo, X))
        e('\t%s\t%s, %s, %s' % (p['add'], vo, vo, t7))
        e('\t%s\t%s, %s, %d' % (p['ror'], X, r, p['s1'][0]))
        e('\t%s\t%s, %s, %d' % (p['ror'], Y, r, p['s1'][1]))
        e('\t%s\t%s, %s, %d' % (p['shr'], Z, r, p['s1'][2]))
        e('\txor\t%s, %s, %s' % (X, X, Y))
        e('\txor\t%s, %s, %s' % (X, X, Z))
        e('\t%s\t%s, %s, %s' % (p['add'], r, vo, X))
        e('\t%s\t%s, %d(%s)' % (p['load'], Y, q * wb, KP))
        e('\t%s\t%s, %d(sp)' % (p['store'], r, q * wb))
        st = core(i, st, r, Y)
    assert st == STATE
    e('\taddi\t%s, %s, %d' % (KP, KP, 16 * wb))
    e('\tbne\t%s, %s, 2b' % (KP, KEND))
    for k, r in enumerate(STATE):
        e('\t%s\t%s, %d(a0)' % (p['load'], X, k * wb))
        e('\t%s\t%s, %s, %s' % (p['add'], r, r, X))
        e('\t%s\t%s, %d(a0)' % (p['store'], r, k * wb))
    e('\taddi\t%s, %s, %d' % (KP, KP, -rounds * wb))
    e('\taddi\ta1, a1, %d' % (16 * wb))
    e('\tbne\ta1, a2, 1b')
    for k in range(0, 16 * wb, 8):
        e('\tsd\tzero, %d(sp)' % k)
    for k, r in enumerate(SAVED):
        e('\tld\t%s, %d(sp)' % (r, 16 * wb + 8 * k))
    e('\taddi\tsp, sp, %d' % frame)
    e('9:')
    e('\tret')
    if flavor == 'go':
        return go_text(bits, body)
    ninsn = sum(1 for l in body if l.startswith('\t') and not l.startswith('\t.'))
    out = []
    if flavor == 'openssl':
        out.append(HEAD % dict(bits=bits, name=name, wbits=wb * 8, loops=(rounds - 16) // 16, size=ninsn * 4))
        out.append('\t.text\n\t.option push\n\t.option arch, +xtheadbb\n\t.globl %s\n\t.hidden %s\n\t.type %s,@function\n\t.p2align 2\n%s:'
                   % (name, name, name, name))
    else:
        out.append('\t.text\n\t.option push\n\t.option arch, +xtheadbb\n\t.p2align 2\n\t.globl %s\n\t.type %s,@function\n%s:' % (name, name, name))
    out += body
    out.append('\t.size %s, .-%s' % (name, name))
    out.append('\t.option pop')
    out.append('')
    out.append('\t.section .rodata')
    out.append('\t.p2align 6')
    out.append('.L%s_K:' % name)
    for k in p['K']:
        out.append('\t%s\t0x%0*x' % (p['kdir'], wb * 2, k))
    if flavor == 'openssl':
        out.append('')
        out.append('\t.section .note.GNU-stack,"",@progbits')
    return '\n'.join(out) + '\n'


# Go assembler: register numbers; t6 (X31) is the assembler's temporary, so
# its role goes to X23. X1-X4, X26 and X27 are not used.
GOREG = {'zero': 'X0', 'sp': 'X2', 't0': 'X5', 't1': 'X6', 't2': 'X7', 's0': 'X8', 's1': 'X9',
         'a0': 'X10', 'a1': 'X11', 'a2': 'X12', 'a3': 'X13', 'a4': 'X14', 'a5': 'X15', 'a6': 'X16', 'a7': 'X17',
         's2': 'X18', 's3': 'X19', 's4': 'X20', 's5': 'X21', 's6': 'X22', 't6': 'X23',
         't3': 'X28', 't4': 'X29', 't5': 'X30'}
GOHEAD = '''// Code generated by gen_sha2_c906.py --bits %(bits)d --flavor go. DO NOT EDIT.

// Copyright 2026 The Go Authors. All rights reserved.
// Use of this source code is governed by a BSD-style
// license that can be found in the LICENSE file.

//go:build !purego

#include "textflag.h"

// SHA-%(bits)d block function for the T-Head C906 (NanoKVM OS): rounds 0 to 15,
// then one body of 16 rounds run %(loops)d times. The XTheadBb instructions
// (th.srri, th.srriw, th.rev, th.revw) are WORDs with the mnemonic in a
// comment. See sha%(bits)dblock.go for the Go equivalent.

// func block(dig *Digest, p []byte)
TEXT ·block(SB),0,$%(frame)d-32
	MOV	p_base+8(FP), X11
	MOV	p_len+16(FP), X12
	MOV	dig+0(FP), X10
	SRL	$%(shift)d, X12
	SLL	$%(shift)d, X12
	BEQZ	X12, end
	ADD	X11, X12, X12
	MOV	$·_K(SB), X8
	ADD	$%(ksize)d, X8, X22
'''


def th_word(op, rd, rs, imm=0):
    """Encoding of an XTheadBb instruction (custom-0 opcode, funct3 001)."""
    top = {'th.srri': 0b000100 << 26 | imm << 20, 'th.srriw': 0b0001010 << 25 | imm << 20,
           'th.rev': 0b1000001 << 25, 'th.revw': 0b1001000 << 25}[op]
    return top | rs << 15 | 1 << 12 | rd << 7 | 0x0b


def go_text(bits, body):
    """The GNU instruction lines of gen() from the block loop on, in Go assembler syntax."""
    p = PARAMS[bits]
    wb = p['wb']
    out = [(GOHEAD % dict(bits=bits, loops=(p['rounds'] - 16) // 16, frame=16 * wb, shift=6 if bits == 256 else 7,
                          ksize=p['rounds'] * wb)).rstrip('\n')]
    labels = {'1': 'block', '2': 'schedule'}

    def reg(r):
        return GOREG[r]

    def mem(arg):
        off, _, base = arg.partition('(')
        base = base[:-1]
        return '%d(%s)' % (int(off) + (8 if base == 'sp' else 0), reg(base))   # locals start above the saved LR

    start = body.index('1:')
    stop = next(i for i, l in enumerate(body) if l.startswith('\tbne\ta1, a2, 1b'))
    state_loads = [l for l in body[:start] if l.split('\t')[1] in (p['load'],) and '(a0)' in l]
    assert len(state_loads) == 8
    for line in state_loads + body[start:stop + 1]:
        if line.startswith('\t.'):
            continue
        if line.endswith(':'):
            out.append('')
            out.append(labels[line[:-1]] + ':')
            continue
        op, rest = line.strip().split('\t')
        a = [x.strip() for x in rest.split(',')]
        if op in ('lw', 'ld'):
            out.append('\t%s\t%s, %s' % ('MOVW' if op == 'lw' else 'MOV', mem(a[1]), reg(a[0])))
        elif op in ('sw', 'sd'):
            out.append('\t%s\t%s, %s' % ('MOVW' if op == 'sw' else 'MOV', reg(a[0]), mem(a[1])))
        elif op in ('add', 'addw', 'xor', 'and'):
            out.append('\t%s\t%s, %s, %s' % (op.upper(), reg(a[2]), reg(a[1]), reg(a[0])))
        elif op == 'addi':
            out.append('\tADD\t$%d, %s, %s' % (int(a[2]), reg(a[1]), reg(a[0])))
        elif op in ('srli', 'srliw'):
            out.append('\t%s\t$%d, %s, %s' % ('SRL' if op == 'srli' else 'SRLW', int(a[2]), reg(a[1]), reg(a[0])))
        elif op in ('th.srri', 'th.srriw', 'th.rev', 'th.revw'):
            rd, rs = int(reg(a[0])[1:]), int(reg(a[1])[1:])
            imm = int(a[2]) if len(a) == 3 else 0
            text = '%s x%d, x%d' % (op, rd, rs) + (', %d' % imm if len(a) == 3 else '')
            out.append('\tWORD\t$0x%08x\t// %s' % (th_word(op, rd, rs, imm), text))
        elif op == 'bne':
            out.append('\tBNE\t%s, %s, %s' % (reg(a[0]), reg(a[1]), labels[a[2][:-1]]))
        else:
            raise SystemExit('go_text: unknown instruction %s' % op)
    out.append('')
    out.append('end:')
    out.append('\tRET')
    return '\n'.join(out) + '\n'


def check_words(text, binutils):
    """Every WORD of the Go text against GNU as."""
    import re
    import subprocess
    import tempfile
    words = sorted(set(re.findall(r'WORD\t\$(0x[0-9a-f]{8})\t// (th\.[^\n]+)', text)))
    with tempfile.TemporaryDirectory() as d:
        src = d + '/w.S'
        with open(src, 'w') as f:
            f.write('\t.option arch, +xtheadbb\n' + ''.join('\t%s\n' % m for _, m in words))
        subprocess.run([binutils + 'as', '-march=rv64gc', '-o', d + '/w.o', src], check=True)
        dump = subprocess.run([binutils + 'objdump', '-d', '-M', 'no-aliases', d + '/w.o'], check=True, capture_output=True, text=True).stdout
    got = re.findall(r'^\s*[0-9a-f]+:\s+([0-9a-f]{8})\s', dump, re.M)
    assert len(got) == len(words), (len(got), len(words))
    for (w, m), g in zip(words, got):
        if int(w, 16) != int(g, 16):
            raise SystemExit('encoding of "%s": generator %s, GNU as %s' % (m, w, g))
    return len(words)


M64 = (1 << 64) - 1


def sext32(v):
    v &= 0xffffffff
    return v | (M64 ^ 0xffffffff) if v >> 31 else v


def simulate(text, bits, name, state, data):
    """Execute the generated function; returns the new state words."""
    p = PARAMS[bits]
    wb = p['wb']
    ST, DATA, KT, STACK = 0x1000, 0x10000, 0x200000, 0x800000
    mem = {}

    def store(addr, v, n):
        for k in range(n):
            mem[addr + k] = v >> (8 * k) & 255

    def load(addr, n):
        if DATA <= addr < DATA + len(data):
            return int.from_bytes(data[addr - DATA:addr - DATA + n], 'little')
        return sum(mem[addr + k] << (8 * k) for k in range(n))

    for k, v in enumerate(state):
        store(ST + k * wb, v, wb)
    for k, v in enumerate(p['K']):
        store(KT + k * wb, v, wb)
    code, labels = [], {}
    started = False
    for line in text.split('\n'):
        t = line.strip()
        if t == name + ':':
            started = True
            continue
        if not started or not t or t.startswith(('/*', '*', '#')):
            continue
        if t.startswith('.size'):
            break
        if t.startswith('.'):
            continue
        if t.endswith(':'):
            labels.setdefault(t[:-1], []).append(len(code))
            continue
        op, _, rest = t.partition('\t')
        code.append((op, [a.strip() for a in rest.split(',')]))
    reg = {'zero': 0, 'sp': STACK, 'a0': ST, 'a1': DATA, 'a2': len(data) // (16 * wb), 'ra': 0}
    saved = {r: 0x5a5a000000000000 | k for k, r in enumerate('s%d' % j for j in range(12))}
    reg.update(saved)

    def target(lab, pc):
        cands = labels[lab[:-1]]
        return max(c for c in cands if c <= pc) if lab.endswith('b') else min(c for c in cands if c >= pc)

    def addr(arg):
        off, _, base = arg.partition('(')
        return reg[base[:-1]] + int(off)

    pc = 0
    low = STACK
    while True:
        op, a = code[pc]
        pc += 1
        if op == 'ret':
            break
        elif op == 'beqz':
            if reg[a[0]] == 0:
                pc = target(a[1], pc)
        elif op == 'bne':
            if reg[a[0]] != reg[a[1]]:
                pc = target(a[2], pc)
        elif op == 'addi':
            reg[a[0]] = (reg[a[1]] + int(a[2])) & M64
        elif op == 'add':
            reg[a[0]] = (reg[a[1]] + reg[a[2]]) & M64
        elif op == 'addw':
            reg[a[0]] = sext32(reg[a[1]] + reg[a[2]])
        elif op == 'slli':
            reg[a[0]] = (reg[a[1]] << int(a[2])) & M64
        elif op == 'srli':
            reg[a[0]] = reg[a[1]] >> int(a[2])
        elif op == 'srliw':
            reg[a[0]] = sext32((reg[a[1]] & 0xffffffff) >> int(a[2]))
        elif op == 'th.srri':
            n = int(a[2])
            reg[a[0]] = (reg[a[1]] >> n | reg[a[1]] << (64 - n)) & M64
        elif op == 'th.srriw':
            n, v = int(a[2]), reg[a[1]] & 0xffffffff
            reg[a[0]] = sext32(v >> n | v << (32 - n))
        elif op == 'th.rev':
            reg[a[0]] = int.from_bytes(reg[a[1]].to_bytes(8, 'little'), 'big')
        elif op == 'th.revw':
            reg[a[0]] = sext32(int.from_bytes((reg[a[1]] & 0xffffffff).to_bytes(4, 'little'), 'big'))
        elif op == 'xor':
            reg[a[0]] = reg[a[1]] ^ reg[a[2]]
        elif op == 'and':
            reg[a[0]] = reg[a[1]] & reg[a[2]]
        elif op == 'la':
            reg[a[0]] = KT
        elif op == 'lw':
            reg[a[0]] = sext32(load(addr(a[1]), 4))
        elif op == 'ld':
            reg[a[0]] = load(addr(a[1]), 8)
        elif op == 'sw':
            store(addr(a[1]), reg[a[0]] & 0xffffffff, 4)
        elif op == 'sd':
            store(addr(a[1]), reg[a[0]], 8)
        else:
            raise SystemExit('simulate: unknown instruction %s' % op)
        low = min(low, reg['sp'])
    assert reg['sp'] == STACK, 'sp not restored'
    for r, v in saved.items():
        assert reg[r] == v, '%s not preserved' % r
    if data:
        assert all(mem.get(low + k, 0) == 0 for k in range(16 * wb)), 'message schedule not wiped'
    return [load(ST + k * wb, wb) for k in range(8)]


def reference(bits, state, data):
    """hashlib has no raw compression function: an independent plain implementation."""
    p = PARAMS[bits]
    wb = p['wb']
    n = 8 * wb
    mask = (1 << n) - 1

    def ror(v, k):
        return (v >> k | v << (n - k)) & mask

    s = list(state)
    for off in range(0, len(data), 16 * wb):
        w = [int.from_bytes(data[off + k * wb:off + (k + 1) * wb], 'big') for k in range(16)]
        for i in range(16, p['rounds']):
            x, y = w[i - 15], w[i - 2]
            w.append((w[i - 16] + (ror(x, p['s0'][0]) ^ ror(x, p['s0'][1]) ^ x >> p['s0'][2]) + w[i - 7]
                      + (ror(y, p['s1'][0]) ^ ror(y, p['s1'][1]) ^ y >> p['s1'][2])) & mask)
        a, b, c, d, e, f, g, h = s
        for i in range(p['rounds']):
            t1 = (h + (ror(e, p['S1'][0]) ^ ror(e, p['S1'][1]) ^ ror(e, p['S1'][2])) + ((e & f) ^ (~e & mask & g)) + p['K'][i] + w[i]) & mask
            t2 = ((ror(a, p['S0'][0]) ^ ror(a, p['S0'][1]) ^ ror(a, p['S0'][2])) + ((a & b) ^ (a & c) ^ (b & c))) & mask
            a, b, c, d, e, f, g, h = (t1 + t2) & mask, a, b, c, (d + t1) & mask, e, f, g
        s = [(x + y) & mask for x, y in zip(s, (a, b, c, d, e, f, g, h))]
    return s


IV = {256: [0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19],
      512: [0x6a09e667f3bcc908, 0xbb67ae8584caa73b, 0x3c6ef372fe94f82b, 0xa54ff53a5f1d36f1,
            0x510e527fade682d1, 0x9b05688c2b3e6c1f, 0x1f83d9abfb41bd6b, 0x5be0cd19137e2179]}


def selftest(cases):
    import random
    rnd = random.Random(1)
    for bits in (256, 512):
        p = PARAMS[bits]
        wb = p['wb']
        text = gen(bits, 'sha_test', 'openssl')
        # the reference itself against hashlib: one padded block of "abc"
        block = b'abc' + b'\x80' + bytes(16 * wb - 4 - 2 * wb) + (24).to_bytes(2 * wb, 'big')
        digest = b''.join(v.to_bytes(wb, 'big') for v in reference(bits, IV[bits], block))
        assert digest == (hashlib.sha256 if bits == 256 else hashlib.sha512)(b'abc').digest()
        for case in range(cases):
            blocks = case % 4
            data = rnd.randbytes(16 * wb * blocks)
            state = [rnd.getrandbits(wb * 8) for _ in range(8)]
            got = simulate(text, bits, 'sha_test', state, data)
            assert got == reference(bits, state, data), (bits, case)
    print('SHA-256 and SHA-512: %d cases each match the reference (checked against hashlib)' % cases)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--bits', type=int, choices=[256, 512])
    ap.add_argument('--name')
    ap.add_argument('--flavor', choices=['openssl', 'plain', 'go'], default='openssl')
    ap.add_argument('--output')
    ap.add_argument('--check-file', metavar='FILE', help='FILE must be the generated assembly')
    ap.add_argument('--binutils', metavar='PREFIX', help='with --flavor go: check every WORD against PREFIXas')
    ap.add_argument('--check', nargs=2, metavar=('PATCH', 'PATH'), help='the file PATH added by PATCH must be the generated assembly')
    ap.add_argument('--selftest', type=int, metavar='CASES')
    a = ap.parse_args()
    if a.selftest:
        selftest(a.selftest)
    if a.check:
        patch, path = a.check
        section = open(patch).read().split('\n+++ b/%s\n' % path, 1)[1].split('\n--- ', 1)[0]
        added = ''.join(line[1:] + '\n' for line in section.split('\n') if line.startswith('+'))
        if added != gen(a.bits, a.name, a.flavor):
            sys.exit('%s: %s is not the generated SHA-%d assembly' % (patch, path, a.bits))
        print('%s: %s is up to date' % (patch, path))
    if a.check_file:
        if open(a.check_file).read() != gen(a.bits, a.name, a.flavor):
            sys.exit('%s is not the generated SHA-%d assembly' % (a.check_file, a.bits))
        print('%s: up to date' % a.check_file)
    if a.binutils:
        print('%d XTheadBb encodings match GNU as' % check_words(gen(a.bits, a.name, 'go'), a.binutils))
    if a.output:
        with open(a.output, 'w') as f:
            f.write(gen(a.bits, a.name, a.flavor))


if __name__ == '__main__':
    main()
