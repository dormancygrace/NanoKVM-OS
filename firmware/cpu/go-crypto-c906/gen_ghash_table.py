#!/usr/bin/env python3
"""Generate GHASH for the T-Head C906 with 8-bit tables (Shoup's method).

    void NAME(u64 acc[2], const u64 *tables, const u8 *data, size_t nblocks);

acc is {lo, hi} in the POLYVAL form of the kernel's lib/crypto/gf128hash.c:
lo = be64(Xi + 8), hi = be64(Xi) for the GHASH value Xi. Per block:
acc ^= the byte-swapped block; acc = acc * H. data may have any alignment
and nblocks may be 0.

tables holds N tables of 4 KiB, N = 1, 2 or 4. Table q is u64 lo[256] followed
by u64 hi[256]; entry b is b * H * x^(128 q / N), where bit 7 of b is the
coefficient of the lowest power (see prepare_tables() in the test and the C
glue of each consumer). A block is N interleaved Horner chains: 16 / N steps
of 8 bits, each step one lookup per table and one lookup in the constant
reduction table for the 8 bits shifted out.

The C906 has no carry-less multiply, and its integer multiplier is slow for
operands above 32 bits. Emulating the product with integer multiplies
(the previous code) costs about 390 cycles per block. Table lookups cost
about 200 / 140 / 113 cycles for 1 / 2 / 4 tables while the tables are in the
64 KiB L1 data cache. There is no L2 cache: a table evicted between messages
costs about 110 ns per line to bring back.

Table lookups depend on the key and the data, as in OpenSSL's portable 4-bit
code. This is not constant-time code.

--flavor go writes the same instruction stream in Go assembler syntax as
ghashBlocksC906(acc, tables, data, nblocks, rtab): the constant reduction
table is an argument (Go code holds it), the T-Head instructions are WORDs
checked against GNU as (--binutils), X20 takes the place of t6, and nothing
is saved, as Go's ABI0 has no callee-saved registers.

Usage: gen_ghash_table.py --flavor linux|openssl|plain|go --tables N --name NAME
       (--output FILE | --check PATCH | --check-file FILE) [--binutils PREFIX]
"""
import argparse

import goasm_c906


def rtable():
    """R[r]: what the 8 bits r shifted out of the low end fold back into the top 16 bits."""
    out = []
    for r in range(256):
        v = 0
        for j in range(8):
            if r >> j & 1:
                v ^= 0xe100 >> (7 - j)
        out.append(v << 48)
    return out


