#!/usr/bin/env python3
"""Check platform output hashes, toolchain inputs and package payload assembly."""

import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

REPO = Path(__file__).resolve().parents[1]


def build(tree, out, *steps):
    return subprocess.run(["bash", str(tree / "platform/build.sh"), "-o", str(out), *steps],
                          capture_output=True, text=True)


def expect(result, success, name, text=None):
    assert (result.returncode == 0) == success, (name, result.stdout, result.stderr)
    if text is not None:
        assert text in result.stdout + result.stderr, (name, text, result.stdout, result.stderr)
    print(f"{name}: pass")


with tempfile.TemporaryDirectory(prefix="nkos-platform-") as directory:
    root = Path(directory)
    # A minimal checkout: build.sh and its lists, the release name and a
    # stand-in for firmware/buildroot.
    tree = root / "repo"
    shutil.copytree(REPO / "platform", tree / "platform",
                    ignore=shutil.ignore_patterns("*.patch", "*.bin", "sg2002-aes"))
    (tree / "scripts").mkdir()
    shutil.copy(REPO / "scripts/nanokvm_cpu_profile.py", tree / "scripts/")
    (tree / "firmware/alpine").mkdir(parents=True)
    shutil.copy(REPO / "firmware/alpine/release.env", tree / "firmware/alpine/release.env")
    defconfig = tree / "firmware/buildroot/configs/nanokvm_platform_defconfig"
    defconfig.parent.mkdir(parents=True)
    defconfig.write_text("BR2_riscv=y\n")
    out = root / "out"
    images = out / "images"

    images.mkdir(parents=True)
    expect(build(tree, out, "hashes"), False, "empty output tree is rejected", "No build outputs")
    (images / "SHA256SUMS").write_text("old manifest\n")
    expect(build(tree, out, "hashes"), False, "manifest alone is not a build", "No build outputs")

    outputs = {"Image": b"kernel", "u-boot.bin": b"loader", "boot/alpha.sd": b"fit"}
    for name, data in outputs.items():
        (images / name).parent.mkdir(parents=True, exist_ok=True)
        (images / name).write_bytes(data)
    listed = "".join(f"{hashlib.sha256(outputs[name]).hexdigest()}  {name}\n" for name in sorted(outputs))
    expect(build(tree, out, "hashes"), True, "hashes of every output", "3 outputs")
    assert (images / "SHA256SUMS").read_text() == listed, (images / "SHA256SUMS").read_text()
    expect(build(tree, out, "hashes"), True, "hashes leave out their own SHA256SUMS", "3 outputs")
    assert (images / "SHA256SUMS").read_text() == listed
    (images / "fip.bin").write_bytes(b"new")
    expect(build(tree, out, "hashes"), True, "a new output is listed", "4 outputs")
    assert "fip.bin" in (images / "SHA256SUMS").read_text()
    (images / "fip.bin").unlink()

    # The toolchain is reused only if it was built from the current inputs.
    stamp = out / "buildroot-output/.platform-toolchain"
    stamp.parent.mkdir(parents=True)
    stamp.write_text("previous inputs\n")
    result = build(tree, out, "toolchain")
    expect(result, False, "toolchain from other inputs is rejected", "Delete")
    current = re.search(r"current:\s+([0-9a-f]{64})", result.stderr).group(1)
    stamp.write_text(current + "\n")
    expect(build(tree, out, "toolchain"), True, "unchanged inputs reuse the toolchain", "already built")
    defconfig.write_text("BR2_riscv=y\nBR2_CCACHE=y\n")
    expect(build(tree, out, "toolchain"), False, "changed Buildroot configuration is rejected", current)
    defconfig.write_text("BR2_riscv=y\n")
    lock = tree / "platform/sources.lock"
    original = lock.read_text()
    lock.write_text(re.sub(r"(?m)^(buildroot\s+\S+\s+)\S+", r"\g<1>" + "0" * 64, original))
    expect(build(tree, out, "toolchain"), False, "changed Buildroot archive pin is rejected")
    lock.write_text(original)
    expect(build(tree, out, "toolchain"), True, "restored inputs reuse the toolchain again")

    # An interrupted build from other inputs is not continued either.
    stamp.unlink()
    (out / "buildroot").mkdir()
    (out / "buildroot/.platform-patched").write_text("previous inputs\n")
    expect(build(tree, out, "toolchain"), False, "interrupted build from other inputs is rejected", "Delete")

    # Assemble the real primary manifest, using repository files unchanged and
    # stand-ins only for cross-built outputs. Legacy staging scripts are not
    # involved, so a missing primary manifest entry cannot be hidden by them.
    for line in (tree / "platform/packages.list").read_text().splitlines():
        fields = line.split()
        if not fields or fields[0].startswith("#") or fields[1] not in ("file", "tree"):
            continue
        _, kind, _, _, name = fields
        if name.startswith("%"):
            continue  # Generated by the real payloads step.
        if name.startswith("@"):
            destination = images / name[1:]
            if kind == "tree":
                destination = destination / "fixture"
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(b"cross-built fixture\n")
        else:
            destination = tree / name
            destination.parent.mkdir(parents=True, exist_ok=True)
            if kind == "tree":
                shutil.copytree(REPO / name, destination, dirs_exist_ok=True)
            else:
                shutil.copyfile(REPO / name, destination)
    host_python = out / "buildroot-output/host/bin/python3"
    host_python.parent.mkdir(parents=True, exist_ok=True)
    host_python.symlink_to(sys.executable)
    # A previous debug invocation must not become a release package merely
    # because the next shell omitted NANOKVM_KERNEL_PROFILE.
    release_metadata = images / "boot/kernel.release"
    saved_metadata = release_metadata.read_bytes() if release_metadata.exists() else None
    release_metadata.write_text("7.3.0-nanokvm-os-r3-debug\n")
    expect(build(tree, out, "payloads"), False, "debug artifacts reject release payloads", "Output kernel profile is debug")
    assert not (out / "payloads").exists(), "profile mismatch mutated payloads"
    if saved_metadata is None:
        release_metadata.unlink()
    else:
        release_metadata.write_bytes(saved_metadata)
    marker = out / ".kernel-profile"
    marker.write_text("debug\n")
    for step in ("kernel", "modules", "initramfs", "boot", "payloads"):
        expect(build(tree, out, step), False, f"persisted debug profile rejects release {step}", "Output kernel profile is debug")
    marker.unlink()
    expect(build(tree, out, "payloads"), True, "primary package payload assembly")
    assert marker.read_text() == "release\n"
    debug_env = dict(os.environ, NANOKVM_KERNEL_PROFILE="debug")
    result = subprocess.run(["bash", str(tree / "platform/build.sh"), "-o", str(out), "kernel"],
                            env=debug_env, capture_output=True, text=True)
    expect(result, False, "release artifacts reject debug rebuild", "Output kernel profile is release")
    for step in ("payloads", "packages", "rootfs", "image"):
        result = subprocess.run(["bash", str(tree / "platform/build.sh"), "-o", str(root / "debug"), step],
                                env=debug_env, capture_output=True, text=True)
        expect(result, False, f"debug {step} needs test keys", "need -d (test keys)")
    # -e already excludes -d, so a debug package can only carry test keys.
    result = subprocess.run(["bash", str(tree / "platform/build.sh"), "-o", str(root / "debug"),
                             "-e", __file__, "-d", "packages"],
                            env=debug_env, capture_output=True, text=True)
    expect(result, False, "debug packages refuse release keys", "-e excludes -d")

    app = out / "payloads/app/kvmapp"
    assert {path.name for path in (app / "system/init.d").iterdir()} == {
        "S03usbdev", "S03usbhid", "S15kvmhwd",
        "S95nanokvm", "S96picoclaw", "nanokvm-server-supervisor",
    }, "app payload must contain only its supported init scripts"
    base = out / "payloads/base"
    assert (base / "usr/libexec/nanokvm/legacy/S50avahi-daemon").read_bytes() == (REPO / "firmware/alpine/compat/S50avahi-daemon").read_bytes()
    assert (base / "etc/init.d/S50avahi-daemon").readlink() == Path("/usr/libexec/nanokvm/legacy/S50avahi-daemon")
    supervisor_path = "system/init.d/nanokvm-server-supervisor"
    supervisor = app / supervisor_path
    assert supervisor.is_file() and not supervisor.is_symlink(), "supervisor missing from app payload"
    assert supervisor.stat().st_mode & 0o7777 == 0o755, "supervisor must be installed with mode 0755"
    assert supervisor.read_bytes() == (REPO / "kvmapp" / supervisor_path).read_bytes()
    manifest_path = app / "build-manifest.json"
    manifest = json.loads(manifest_path.read_text())
    release_values = dict(line.split("=", 1) for line in
                          (tree / "firmware/alpine/release.env").read_text().splitlines()
                          if line and not line.startswith("#"))
    # The release version and source commit belong to nanokvm-release only, so
    # that the application package changes only when its files do.
    assert set(manifest) == {"files"}, "the application manifest lists file hashes only"
    assert not (app / "version").exists(), "/kvmapp/version belongs to nanokvm-release"
    release = out / "payloads/release"
    assert (release / "kvmapp/version").read_text().strip() == release_values["NANOKVM_VERSION"].removeprefix("v")
    release_file = (release / "etc/nanokvm-release").read_text()
    assert f'VERSION="{release_values["NANOKVM_VERSION"]}"' in release_file
    assert 'SOURCE_COMMIT="' in release_file
    expected_files = {str(path.relative_to(app)): hashlib.sha256(path.read_bytes()).hexdigest()
                      for path in app.rglob("*")
                      if path.is_file() and not path.is_symlink() and path != manifest_path}
    assert manifest["files"] == expected_files, "manifest must hash every payload file, excluding itself and symlinks"
    web = out / "payloads/web/kvmapp"
    web_manifest_path = web / "web-build-manifest.json"
    web_manifest = json.loads(web_manifest_path.read_text())
    assert not (app / "server/web").exists(), "backend must not own browser assets"
    assert not any(name.startswith("server/web/") for name in manifest["files"])
    assert set(web_manifest) == {"files"}, "the web manifest lists file hashes only"
    assert web_manifest["files"] == {
        str(path.relative_to(web)): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in web.rglob("*") if path.is_file() and path != web_manifest_path
    }
    assert (web / "server/web/fixture").exists(), "web package must own browser assets"
    assert not (app / "enhanced-stage-manifest.json").exists(), "obsolete stage manifest retained"
    # The release button supplies versions without modifying release.env.
    result = subprocess.run(["bash", str(tree / "platform/build.sh"), "-o", str(out), "payloads"],
                            env={**os.environ, "NANOKVM_VERSION": "v9.8.7"},
                            capture_output=True, text=True)
    expect(result, True, "workflow version overrides release.env")
    assert (release / "kvmapp/version").read_text().strip() == "9.8.7"
    assert 'VERSION="v9.8.7"' in (release / "etc/nanokvm-release").read_text()
    assert json.loads(manifest_path.read_text()) == manifest
    assert json.loads(web_manifest_path.read_text()) == web_manifest
    # Execute the installed file directly: this checks its shebang and mode as
    # well as its presence, without starting target binaries or touching /run.
    expect(subprocess.run([str(supervisor), "wait"], capture_output=True, text=True,
                          env={**os.environ, "NANOKVM_RECOVERY_DIR": str(root / "recovery")},
                          timeout=5), True, "packaged supervisor is executable")

    # The debug profile must also have a working positive path with test keys.
    # Use the existing payload fixture with matching debug boot metadata.
    marker.unlink()
    release_metadata.write_text("7.3.0-nanokvm-os-r3-debug\n")
    result = subprocess.run(["bash", str(tree / "platform/build.sh"), "-o", str(out),
                             "-d", "payloads"], env=debug_env, capture_output=True, text=True)
    expect(result, True, "debug payloads accept test keys")
    assert marker.read_text() == "debug\n"
    assert (out / "payloads/kernel-sg2002/usr/lib/nanokvm/boot/kernel.release").read_bytes() == release_metadata.read_bytes()

# Exercise the real startup/mapping synchronization without creating namespaces.
source = (REPO / "platform/build.sh").read_text()
userns = source[source.index("in_userns() ("):source.index("\nqemu=")]
for mode, code in (("startup-fails", 17), ("uidmap-fails", 23),
                   ("gidmap-fails", 24), ("child-fails", 29), ("success", 0)):
    with tempfile.TemporaryDirectory(prefix="nkos-userns-") as directory:
        root = Path(directory)
        script = root / "test.sh"
        script.write_text("""#!/bin/bash
set -euo pipefail
mode=$1
export TMPDIR=$2
here=$2 out=$2 jobs=1 key=
awk() { echo 100000; }
newuidmap() { [ "$mode" != uidmap-fails ] || return 23; }
newgidmap() { [ "$mode" != gidmap-fails ] || return 24; }
unshare() {
    [ "$mode" != startup-fails ] || return 17
    echo "$BASHPID" > "$TMPDIR/child.pid"
    echo > "$sync/ready"
    read -r _ < "$sync/mapped"
    [ "$mode" != child-fails ] || return 29
}
""" + userns + "\nin_userns packages\n")
        result = subprocess.run(["bash", str(script), mode, directory],
                                capture_output=True, text=True, timeout=5)
        assert result.returncode == code, (mode, result.returncode, result.stderr)
        assert not list(root.glob("tmp.*")), (mode, "synchronization files left behind")
        child = root / "child.pid"
        if child.exists():
            assert not Path("/proc", child.read_text().strip()).exists(), (mode, "child left running")
        print(f"namespace {mode}: pass")
