func TestAssetsServePrecompressedHashedFiles(t *testing.T) {
	gin.SetMode(gin.TestMode)
	dir := t.TempDir()
	os.MkdirAll(filepath.Join(dir, "assets"), 0755)
	os.WriteFile(filepath.Join(dir, "index.html"), []byte("<html>"), 0644)
	os.WriteFile(filepath.Join(dir, "assets", "app-abc.js"), []byte("plain"), 0644)
	os.WriteFile(filepath.Join(dir, "assets", "small-abc.js"), []byte("small"), 0644)
	gz, _ := os.Create(filepath.Join(dir, "assets", "app-abc.js.gz"))
	w := gzip.NewWriter(gz)
	w.Write([]byte("compressed"))
	w.Close()
	gz.Close()

	r := gin.New()
	r.Use(assets(dir))
	r.Use(static.Serve("/", static.LocalFile(dir, true)))
	get := func(path, encoding string) *httptest.ResponseRecorder {
		req := httptest.NewRequest("GET", path, nil)
		if encoding != "" {
			req.Header.Set("Accept-Encoding", encoding)
		}
		rec := httptest.NewRecorder()
		r.ServeHTTP(rec, req)
		return rec
	}

	rec := get("/assets/app-abc.js", "br, gzip;q=0.8")
	if rec.Code != http.StatusOK || rec.Header().Get("Content-Encoding") != "gzip" {
		t.Fatalf("gzip: %d %v", rec.Code, rec.Header())
	}
	if kind := rec.Header().Get("Content-Type"); kind != "text/javascript; charset=utf-8" {
		t.Fatalf("content type %q", kind)
	}
	body, _ := gzip.NewReader(rec.Body)
	if data, _ := io.ReadAll(body); string(data) != "compressed" {
		t.Fatalf("body %q", data)
	}
	if rec.Header().Get("Cache-Control") != "public, max-age=31536000, immutable" {
		t.Fatalf("cache %q", rec.Header().Get("Cache-Control"))
	}

	for _, encoding := range []string{"", "identity", "gzip;q=0"} {
		rec = get("/assets/app-abc.js", encoding)
		if rec.Header().Get("Content-Encoding") != "" || rec.Body.String() != "plain" {
			t.Fatalf("%q: %v %q", encoding, rec.Header(), rec.Body.String())
		}
	}
	// No .gz: the plain file, still cacheable.
	rec = get("/assets/small-abc.js", "gzip")
	if rec.Body.String() != "small" || rec.Header().Get("Cache-Control") == "" {
		t.Fatalf("small: %v %q", rec.Header(), rec.Body.String())
	}
	// A missing hashed asset (e.g. mid-update) is an uncached 404, even when
	// a stray .gz exists.
	os.WriteFile(filepath.Join(dir, "assets", "orphan-abc.js.gz"), []byte("x"), 0644)
	for _, missing := range []string{"/assets/not-yet-installed-abc.js", "/assets/orphan-abc.js"} {
		rec = get(missing, "gzip")
		if rec.Code != http.StatusNotFound || rec.Header().Get("Cache-Control") != "" ||
			rec.Header().Get("Content-Encoding") != "" {
			t.Fatalf("%s: %d %v", missing, rec.Code, rec.Header())
		}
	}
	// Outside /assets nothing changes, and paths cannot climb out of it.
	if rec = get("/index.html", "gzip"); rec.Header().Get("Cache-Control") != "" {
		t.Fatalf("index: %v", rec.Header())
	}
	if rec = get("/assets/../index.html", "gzip"); rec.Header().Get("Content-Encoding") != "" {
		t.Fatalf("traversal: %v", rec.Header())
	}
}

func TestAssetsBrotliNegotiation(t *testing.T) {
	gin.SetMode(gin.TestMode)
	dir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(dir, "assets"), 0755); err != nil {
		t.Fatal(err)
	}
	plain := []byte("asset payload")
	// A valid Brotli representation generated by node:zlib; no runtime codec
	// library is needed because the handler serves the build's bytes verbatim.
	br := []byte{11, 6, 128, 97, 115, 115, 101, 116, 32, 112, 97, 121, 108, 111, 97, 100, 3}
	var gz bytes.Buffer
	writer := gzip.NewWriter(&gz)
	if _, err := writer.Write(plain); err != nil {
		t.Fatal(err)
	}
	if err := writer.Close(); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"both.js", "gzip-only.js", "br-only.js", "plain.js"} {
		variants := map[string][]byte{"": plain}
		if name == "both.js" || name == "gzip-only.js" {
			variants[".gz"] = gz.Bytes()
		}
		if name == "both.js" || name == "br-only.js" {
			variants[".br"] = br
		}
		for suffix, data := range variants {
			if err := os.WriteFile(filepath.Join(dir, "assets", name+suffix), data, 0644); err != nil {
				t.Fatal(err)
			}
		}
	}
	r := gin.New()
	r.Use(assets(dir), static.Serve("/", static.LocalFile(dir, true)))
	for _, tc := range []struct {
		name, file, header, coding string
		status                     int
	}{
		{"no header", "both.js", "", "", 200},
		{"Brotli wins equal quality", "both.js", "gzip, deflate, br, zstd", "br", 200},
		{"gzip preferred", "both.js", "br;q=0.4, gzip;q=0.8", "gzip", 200},
		{"Brotli preferred", "both.js", "br;q=0.8, gzip;q=0.4", "br", 200},
		{"case and whitespace", "both.js", " BR ; Q=1.000, GZIP;q=0.5", "br", 200},
		{"Brotli disabled", "both.js", "br;q=0, gzip", "gzip", 200},
		{"both disabled", "both.js", "br;q=0.000, gzip;q=0", "", 200},
		{"wildcard", "both.js", "*;q=0.5", "br", 200},
		{"explicit overrides wildcard", "both.js", "br;q=0, *;q=1", "gzip", 200},
		{"explicit gzip overrides wildcard zero", "both.js", "*;q=0,gzip", "gzip", 200},
		{"everything disabled", "both.js", "*;q=0", "", 406},
		{"identity preference", "both.js", "identity;q=1, br;q=0.5, gzip;q=0.4", "", 200},
		{"identity fallback forbidden", "plain.js", "br,identity;q=0", "", 406},
		{"identity overrides wildcard", "plain.js", "*;q=0,identity", "", 200},
		{"missing Brotli fallback", "gzip-only.js", "br,gzip", "gzip", 200},
		{"missing gzip fallback", "br-only.js", "gzip,br;q=0.9", "br", 200},
		{"missing both fallback", "plain.js", "br,gzip", "", 200},
		{"unsupported encoding", "both.js", "zstd", "", 200},
		{"invalid quality", "both.js", "br;q=NaN,gzip", "gzip", 200},
		{"quality out of range", "both.js", "br;q=1.1,gzip", "gzip", 200},
		{"excess precision", "both.js", "br;q=0.0001,gzip", "gzip", 200},
		{"duplicate prohibition", "both.js", "br,br;q=0,gzip", "gzip", 200},
		{"duplicate weight", "both.js", "br;q=0;q=1,gzip", "gzip", 200},
	} {
		t.Run(tc.name, func(t *testing.T) {
			req := httptest.NewRequest(http.MethodGet, "/assets/"+tc.file, nil)
			req.Header.Set("Accept-Encoding", tc.header)
			rec := httptest.NewRecorder()
			r.ServeHTTP(rec, req)
			if rec.Code != tc.status || rec.Header().Get("Content-Encoding") != tc.coding {
				t.Fatalf("response: %d %v", rec.Code, rec.Header())
			}
			if rec.Header().Get("Vary") != "Accept-Encoding" {
				t.Fatalf("Vary: %v", rec.Header())
			}
			if tc.status == 406 {
				if rec.Header().Get("Cache-Control") != "" {
					t.Fatal("unacceptable response must not be cached as immutable")
				}
				return
			}
			want := plain
			if tc.coding == "br" {
				want = br
			} else if tc.coding == "gzip" {
				want = gz.Bytes()
			}
			if !bytes.Equal(rec.Body.Bytes(), want) {
				t.Fatalf("body: %x, want %x", rec.Body.Bytes(), want)
			}
			if rec.Header().Get("Content-Type") != "text/javascript; charset=utf-8" || rec.Header().Get("Cache-Control") != "public, max-age=31536000, immutable" {
				t.Fatalf("headers: %v", rec.Header())
			}
		})
	}
	request := func(method string, fields map[string][]string) *httptest.ResponseRecorder {
		req := httptest.NewRequest(method, "/assets/both.js", nil)
		for key, values := range fields {
			req.Header[key] = values
		}
		rec := httptest.NewRecorder()
		r.ServeHTTP(rec, req)
		return rec
	}
	head := request(http.MethodHead, map[string][]string{"Accept-Encoding": {"gzip;q=0.5", "br"}})
	if head.Code != 200 || head.Header().Get("Content-Encoding") != "br" || head.Body.Len() != 0 || head.Header().Get("Content-Length") != strconv.Itoa(len(br)) {
		t.Fatalf("HEAD: %d %v %q", head.Code, head.Header(), head.Body.String())
	}
	cached := request(http.MethodGet, map[string][]string{"Accept-Encoding": {"br"}, "If-Modified-Since": {head.Header().Get("Last-Modified")}})
	if cached.Code != http.StatusNotModified || cached.Body.Len() != 0 || cached.Header().Get("Vary") != "Accept-Encoding" {
		t.Fatalf("conditional GET: %d %v", cached.Code, cached.Header())
	}
	ranged := request(http.MethodGet, map[string][]string{"Accept-Encoding": {"br"}, "Range": {"bytes=0-3"}})
	if ranged.Code != http.StatusPartialContent || ranged.Header().Get("Content-Encoding") != "br" || !bytes.Equal(ranged.Body.Bytes(), br[:4]) {
		t.Fatalf("range: %d %v %x", ranged.Code, ranged.Header(), ranged.Body.Bytes())
	}
}
