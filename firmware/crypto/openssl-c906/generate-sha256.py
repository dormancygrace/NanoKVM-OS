#!/usr/bin/env python3
"""Adapt the BSD Go C906 SHA-256 compression core to the GNU/OpenSSL ABI."""
import argparse
import ast
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[3]
NAME = 'ossl_sha256_c906_blocks'
SAVED = (8, 9, 18, 19, 20, 21)
FRAME = 64 + 8 * len(SAVED)
K = ('0x428a2f98', '0x71374491', '0xb5c0fbcf', '0xe9b5dba5', '0x3956c25b', '0x59f111f1', '0x923f82a4', '0xab1c5ed5', '0xd807aa98', '0x12835b01', '0x243185be', '0x550c7dc3', '0x72be5d74', '0x80deb1fe', '0x9bdc06a7', '0xc19bf174', '0xe49b69c1', '0xefbe4786', '0x0fc19dc6', '0x240ca1cc', '0x2de92c6f', '0x4a7484aa', '0x5cb0a9dc', '0x76f988da', '0x983e5152', '0xa831c66d', '0xb00327c8', '0xbf597fc7', '0xc6e00bf3', '0xd5a79147', '0x06ca6351', '0x14292967', '0x27b70a85', '0x2e1b2138', '0x4d2c6dfc', '0x53380d13', '0x650a7354', '0x766a0abb', '0x81c2c92e', '0x92722c85', '0xa2bfe8a1', '0xa81a664b', '0xc24b8b70', '0xc76c51a3', '0xd192e819', '0xd6990624', '0xf40e3585', '0x106aa070', '0x19a4c116', '0x1e376c08', '0x2748774c', '0x34b0bcb5', '0x391c0cb3', '0x4ed8aa4a', '0x5b9cca4f', '0x682e6ff3', '0x748f82ee', '0x78a5636f', '0x84c87814', '0x8cc70208', '0x90befffa', '0xa4506ceb', '0xbef9a3f7', '0xc67178f2')


def integer(expr):
    node = ast.parse(expr, mode='eval').body
    def visit(n):
        if isinstance(n, ast.Constant) and type(n.value) is int:
            return n.value
        if isinstance(n, ast.UnaryOp) and isinstance(n.op, ast.USub):
            return -visit(n.operand)
        if isinstance(n, ast.BinOp):
            a, b = visit(n.left), visit(n.right)
            if isinstance(n.op, ast.Add): return a + b
            if isinstance(n.op, ast.Sub): return a - b
            if isinstance(n.op, ast.Mult): return a * b
            if isinstance(n.op, ast.BitAnd): return a & b
        raise ValueError('unsupported constant expression: ' + expr)
    return visit(node)


def reg(s):
    if not re.fullmatch(r'X\d+', s): raise ValueError(s)
    return s.lower()


def memory(s):
    m = re.fullmatch(r'(.*)\((X\d+)\)', s)
    return str(integer(m[1] or '0')) + '(' + reg(m[2]) + ')' if m else None


def render():
    source = ROOT / 'firmware/cpu/go-crypto-c906/sha256block_c906_riscv64.s'
    out = ['/* SPDX-License-Identifier: BSD-3-Clause */',
           '/* Copyright 2023 The Go Authors. All rights reserved.',
           ' * Generated by generate-sha256.py from the Go C906 compression core.',
           ' * GNU ABI: a0=state words, a1=input, a2=number of 64-byte blocks.',
           ' * The 64-byte schedule is wiped; all used callee-saved registers are restored.',
           ' */', '.text', '.p2align 2', '.globl ' + NAME, '.hidden ' + NAME,
           '.type ' + NAME + ', @function', NAME + ':',
           'beqz a2, .L_c906_sha256_zero', 'addi sp, sp, -' + str(FRAME)]
    out += [f'sd x{n}, {64 + 8*i}(sp)' for i, n in enumerate(SAVED)]
    out += ['mv x20, a0', 'mv x29, a1', 'slli x30, a2, 6']
    for line in source.read_text().splitlines():
        line = line.split('//')[0].strip()
        if not line or line.startswith(('#', 'TEXT')): continue
        if line.endswith(':'):
            out.append('.L_c906_sha256_' + line); continue
        op, *rest = line.split(None, 1)
        args = [x.strip() for x in rest[0].split(',')] if rest else []
        if op == 'MOV' and any('(FP)' in a for a in args): continue
        if op == 'MOV' and args[0] == '$·_K(SB)':
            out.append(f'lla {reg(args[1])}, .L_c906_sha256_K'); continue
        if op == 'ADD' and args == ['$8', 'X2', 'X19']:
            out.append('mv x19, sp'); continue
        if op == 'WORD':
            out.append('.word ' + args[0][1:]); continue
        if op in ('MOV', 'MOVW', 'MOVWU'):
            a, c = args; ma, mc = memory(a), memory(c)
            if ma: out.append({'MOV':'ld', 'MOVW':'lw', 'MOVWU':'lwu'}[op] + ' ' + reg(c) + ', ' + ma)
            elif mc: out.append({'MOV':'sd', 'MOVW':'sw', 'MOVWU':'sw'}[op] + ' ' + reg(a) + ', ' + mc)
            elif a.startswith('$'): out.append('li ' + reg(c) + ', ' + a[1:])
            else: out.append(('sext.w ' if op == 'MOVW' else 'mv ') + reg(c) + ', ' + reg(a))
        elif op in ('ADD', 'AND', 'OR', 'XOR', 'SRL', 'SLL'):
            a, c = args[:2]; dest = args[2] if len(args) == 3 else c
            out.append(op.lower() + ('i' if a.startswith('$') else '') + ' ' + reg(dest) + ', ' + reg(c) + ', ' + (a[1:] if a.startswith('$') else reg(a)))
        elif op in ('BEQ', 'BNE'):
            out.append(op.lower() + ' ' + reg(args[0]) + ', ' + reg(args[1]) + ', .L_c906_sha256_' + args[2])
        elif op == 'RET':
            out += [f'sd zero, {i}(sp)' for i in range(0, 64, 8)]
            out += [f'ld x{n}, {64 + 8*i}(sp)' for i, n in enumerate(SAVED)]
            out += ['addi sp, sp, ' + str(FRAME), '.L_c906_sha256_zero:', 'ret']
        else: raise ValueError(line)
    out += ['.size ' + NAME + ', .-' + NAME, '.section .rodata', '.p2align 2', '.L_c906_sha256_K:']
    out += ['.word ' + value for value in K]
    out += ['.section .note.GNU-stack,"",@progbits']
    return '\n'.join(out) + '\n'


def main():
    p = argparse.ArgumentParser(description=__doc__)
    group = p.add_mutually_exclusive_group(required=True)
    group.add_argument('--output', type=Path)
    group.add_argument('--check', action='store_true')
    a = p.parse_args(); text = render()
    if a.output:
        a.output.write_text(text)
    else:
        patch = (Path(__file__).parent / '0003-sha256-dma.patch').read_text()
        section = patch.split('+++ b/crypto/sha/sha256-c906.S\n', 1)[1]
        added = []
        for line in section.splitlines()[1:]:
            if line.startswith('--- '): break
            if line.startswith('+'): added.append(line[1:] + '\n')
        if ''.join(added) != text: raise SystemExit('SHA-256 generated assembly differs from patch')
        print('PASS generated C906 SHA-256 GNU ABI adapter')


if __name__ == '__main__':
    main()
