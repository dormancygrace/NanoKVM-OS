#!/usr/bin/env python3
"""Generate nanokvm_memmove_riscv64.s, the XTheadVector copy loop of memmove.

prepare.py makes runtime.memmove jump here for copies of at least
nanokvmVectorMemmoveMin bytes when nanokvmVectorMemmove is set (see
nanokvm_memmove.go). Vector instructions are WORDs, encoded and checked
against GNU as/objdump by the encoder of ../go-crypto-c906/gen_chacha_riscv64.py.

Usage: gen_memmove_c906.py --binutils PREFIX (--output FILE | --check FILE)
"""
from pathlib import Path
import argparse, sys

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'go-crypto-c906'))
from gen_chacha_riscv64 import Asm, vsetvli, vle, vse, verify  # noqa: E402

# Go register numbers. memmove's arguments arrive in X10-X12 (ABIInternal).
TO, FROM, N = 10, 11, 12
FLAGS, END, VL, BYTES = 5, 6, 13, 14
LMUL = 4  # 64 bytes per instruction at VLEN 128; m8 is no faster on the C906


def loop(a, name, sew, backward):
    """Copy N elements of sew bits; TO/FROM point past the end when backward."""
    a.label(name)
    a(vsetvli(VL, N, sew, LMUL))
    if sew == 8:
        step = VL
    else:
        a(f'SLL\t${(sew // 8).bit_length() - 1}, X{VL}, X{BYTES}')
        step = BYTES
    if backward:
        a(f'SUB\tX{step}, X{TO}', f'SUB\tX{step}, X{FROM}')
    a(vle(0, FROM), vse(0, TO))
    if not backward:
        a(f'ADD\tX{step}, X{TO}', f'ADD\tX{step}, X{FROM}')
    a(f'SUB\tX{VL}, X{N}', f'BNEZ\tX{N}, {name}', 'RET')
    a('')


def build():
    a = Asm()
    a('TEXT runtime·nanokvmMemmoveVector(SB),NOSPLIT|NOFRAME,$0')
    a('// X10 = to, X11 = from, X12 = n; n >= nanokvmVectorMemmoveMin, to != from.')
    a('// Whole 8-byte words when to, from and n are multiples of 8: such a copy may')
    a('// move pointers, which the garbage collector must never see half written,')
    a('// so each is one 8-byte element. Other copies hold no pointers: bytes.')
    a(f'OR\tX{TO}, X{FROM}, X{FLAGS}', f'OR\tX{N}, X{FLAGS}', f'AND\t$7, X{FLAGS}')
    a('// Backward only when the destination starts inside the source; each')
    a('// chunk is loaded completely before it is stored.')
    a(f'BLTU\tX{TO}, X{FROM}, forward')
    a(f'ADD\tX{FROM}, X{N}, X{END}', f'BGEU\tX{TO}, X{END}, forward')
    a(f'ADD\tX{N}, X{TO}', f'ADD\tX{N}, X{FROM}')
    a(f'BNEZ\tX{FLAGS}, b_bytes', f'SRL\t$3, X{N}')
    loop(a, 'b_words', 64, True)
    loop(a, 'b_bytes', 8, True)
    a.label('forward')
    a(f'BNEZ\tX{FLAGS}, f_bytes', f'SRL\t$3, X{N}')
    loop(a, 'f_words', 64, False)
    loop(a, 'f_bytes', 8, False)
    return a


HEADER = '''// Code generated by gen_memmove_c906.py; DO NOT EDIT.

// Copyright 2026 NanoKVM OS contributors.
// Use of this source code is governed by a BSD-style license matching Go.

// memmove's copy loop for XTheadVector (T-Head C906, VLEN 128): unit-stride
// loads and stores of LMUL 4 register groups, 64 bytes each. On the SG2002
// the runtime benchmarks copy 64 B-4 KiB at 1.15-1.27x the scalar loops,
// 1.4-2.4x when source and destination alignments differ.
//
// Vector registers are not preserved across calls; this code calls nothing.
// Assembly functions are not asynchronously preempted; the kernel saves
// vector state across context switches and signals.
//
// Go's assembler has no RVV 0.7.1 encodings, so vector instructions are WORDs.
// The generator checks each against GNU as/objdump -march=rv64gc_xtheadvector.

#include "textflag.h"

'''


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--binutils', required=True, help='GNU binutils prefix with XTheadVector support')
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument('--output', type=Path)
    g.add_argument('--check', type=Path)
    args = p.parse_args()
    a = build()
    n = verify(args.binutils, a.vectors)
    text = HEADER + a.render()
    if args.check:
        if args.check.read_text() != text:
            sys.exit(f'{args.check} is not up to date')
        print(f'{args.check}: up to date, {n} distinct vector encodings verified')
    else:
        args.output.write_text(text)
        print(f'{args.output}: {len(a.vectors)} vector instructions, {n} distinct encodings verified')


if __name__ == '__main__':
    main()
