#!/usr/bin/env python3
"""Generate server/internal/annexb/annexb_riscv64.s, the Annex-B start code search.

Each pass loads two overlapping LMUL 8 groups (bytes i and i+1 of up to 128
positions at VLEN 128) and takes the first position where both are zero; a
scalar load checks the third byte. Vector instructions are WORDs, encoded
and checked against GNU as/objdump by the encoder of gen_chacha_riscv64.py.

Usage: gen_annexb_riscv64.py --binutils PREFIX (--output FILE | --check FILE)
"""
from pathlib import Path
import argparse, sys

from gen_chacha_riscv64 import ABI, Asm, OPIVI, OPMVV, V, opv, verify, vle, vsetvli

# Go register numbers.
BASE, LEFT, START, VL, FOUND, NEXT, THIRD = 10, 11, 8, 5, 6, 13, 14


def vmseq_vi(vd, vs2, imm):
    return V(f'th.vmseq.vi v{vd},v{vs2},{imm}', opv(0b011000, 1, vs2, imm, OPIVI, vd))


def vmand_mm(vd, vs2, vs1):
    return V(f'th.vmand.mm v{vd},v{vs2},v{vs1}', opv(0b011001, 1, vs2, vs1, OPMVV, vd))


def vmfirst_m(rd, vs2):
    return V(f'th.vmfirst.m {ABI[rd]},v{vs2}', opv(0b010101, 1, vs2, 0, OPMVV, rd))


def build():
    a = Asm()
    a('// func indexStartCode(b []byte) int')
    a('TEXT ·indexStartCode(SB), NOSPLIT, $0-32')
    a(f'MOV\tb_base+0(FP), X{BASE}', f'MOV\tb_len+8(FP), X{LEFT}', f'MOV\tX{BASE}, X{START}')
    a('// A start code can begin at the first len-2 bytes; none fits in fewer than 3.')
    a(f'MOV\t$3, X{VL}', f'BLTU\tX{LEFT}, X{VL}, missing', f'SUB\t$2, X{LEFT}')
    a.label('loop')
    a(vsetvli(VL, LEFT, 8, 8))
    a(f'ADD\t$1, X{BASE}, X{NEXT}')
    a(vle(8, BASE), vle(16, NEXT))
    a(vmseq_vi(0, 8, 0), vmseq_vi(1, 16, 0), vmand_mm(0, 0, 1), vmfirst_m(FOUND, 0))
    a(f'BGEZ\tX{FOUND}, pair')
    a(f'ADD\tX{VL}, X{BASE}', f'SUB\tX{VL}, X{LEFT}', f'BNEZ\tX{LEFT}, loop')
    a(f'JMP\tmissing')
    a('// 00 00 at BASE+FOUND; the third byte is in the slice. Coded video has')
    a('// such a pair about every 2 KiB (00 00 03), so it is checked here rather')
    a('// than with a third load of every chunk.')
    a.label('pair')
    a(f'ADD\tX{FOUND}, X{BASE}', f'MOVBU\t2(X{BASE}), X{THIRD}', f'MOV\t$1, X{NEXT}')
    a(f'BEQ\tX{THIRD}, X{NEXT}, found')
    a(f'ADD\t$1, X{BASE}', f'SUB\tX{FOUND}, X{LEFT}', f'SUB\t$1, X{LEFT}', f'BNEZ\tX{LEFT}, loop')
    a.label('missing')
    a(f'MOV\t$-1, X{FOUND}', f'MOV\tX{FOUND}, ret+24(FP)', 'RET')
    a.label('found')
    a(f'SUB\tX{START}, X{BASE}', f'MOV\tX{BASE}, ret+24(FP)', 'RET')
    return a


HEADER = '''// Code generated by firmware/cpu/go-crypto-c906/gen_annexb_riscv64.py. DO NOT EDIT.

//go:build linux && riscv64 && !purego

// Annex-B start code search for the T-Head C906 (XTheadVector, VLEN 128).
// Each pass loads bytes i and i+1 of up to 128 positions as two LMUL 8 groups
// and takes the first position where both are zero; a scalar load checks the
// third. Positions stop at len-3, so no byte past the slice is read. On the
// stand's coded video this is about 2.9x bytes.Index (9 KB access units).
//
// Vector registers are not preserved across calls: all vector state is set
// up and consumed within this call, which calls nothing. Assembly functions
// are not asynchronously preempted; the kernel saves vector state across
// context switches and signals. Callers check vector() first.
//
// Go's assembler has no RVV 0.7.1 encodings, so vector instructions are WORDs.
// The generator checks each against GNU as/objdump -march=rv64gc_xtheadvector.

#include "textflag.h"

'''


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--binutils', required=True, help='GNU binutils prefix with XTheadVector support')
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument('--output', type=Path)
    g.add_argument('--check', type=Path)
    args = p.parse_args()
    a = build()
    n = verify(args.binutils, a.vectors)
    text = HEADER + a.render()
    if args.check:
        if args.check.read_text() != text:
            sys.exit(f'{args.check} is not up to date')
        print(f'{args.check}: up to date, {n} distinct vector encodings verified')
    else:
        args.output.write_text(text)
        print(f'{args.output}: {len(a.vectors)} vector instructions, {n} distinct encodings verified')


if __name__ == '__main__':
    main()
